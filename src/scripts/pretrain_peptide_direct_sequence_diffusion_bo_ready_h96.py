# Phase 1 / pretrain_peptide_direct_sequence_diffusion_bo_ready_h96.py
#
# Replacement for: pretrain_peptide_latent_diffusion_search_cost_sampling_h32_z32.py
#
# Purpose
# -------
# This version removes the GRU-VAE tokenizer entirely. The generative model is a
# direct peptide sequence diffusion model trained to reconstruct length-10
# one-hot peptide tensors from Gaussian-noised versions of themselves.
#
# The architecture intentionally stays compact and comparable to the previous
# GRU-VAE experiments:
#   - sequence length: 10
#   - amino-acid vocabulary: 20
#   - GRU hidden size: 32
#   - GRU layers: 2
#   - time embedding: 32
#
# Later BO coordinate
# -------------------
# The raw diffusion search variable is the initial diffusion base noise epsilon with shape
# [10, 20], flattened to d = 200. For Bayesian optimization, this version also
# fits a lower-dimensional PCA-whitened coordinate from DDIM-inverted training
# epsilon vectors:
#
#     z_bo in R^bo_latent_dim -> inverse PCA -> epsilon -> DDIM -> peptide
#
# The raw epsilon coordinate can still be constrained to the Gaussian typical shell:
#     ||epsilon||_2 = sqrt(10 * 20)
#
# This follows the Search-at-the-Cost-of-Sampling idea: use a deterministic
# generator from a spherical latent/noise coordinate to a discrete design.
#
# Generation path:
#     z_bo -> inverse PCA/whitening -> epsilon -> deterministic DDIM reverse process
#     -> x0_hat -> argmax over amino-acid vocabulary at each position -> peptide
#
# ============================================================

