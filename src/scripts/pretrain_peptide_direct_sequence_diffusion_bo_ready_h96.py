def iter_peptide_batches(
    files: List[str],
    peptide_col: str,
    split_col: str,
    split_filter: Optional[str],
    chunksize: int,
    deduplicate: bool,
) -> Iterable[Tuple[List[str], torch.Tensor]]:
    """Yield (peptides, onehot) batches for coordinate fitting/export."""
    seen = set()
    usecols = [peptide_col]
    if split_filter is not None:
        usecols.append(split_col)

    for csv_path in files:
        reader = pd.read_csv(csv_path, usecols=usecols, chunksize=chunksize)
        for chunk in reader:
            if split_filter is not None:
                mask = chunk[split_col].astype(str).str.lower().eq(str(split_filter).lower())
                chunk = chunk.loc[mask]
                if chunk.empty:
                    continue

            peptides: List[str] = []
            for value in chunk[peptide_col].tolist():
                pep = clean_peptide(value)
                if pep is None:
                    continue
                if deduplicate and pep in seen:
                    continue
                seen.add(pep)
                peptides.append(pep)

            if peptides:
                yield peptides, onehot_encode_peptides(peptides)


@torch.no_grad()
def collect_inverted_epsilon_matrix(
    model: DirectSequenceDiffusion,
    files: List[str],
    args: argparse.Namespace,
    split_filter: str,
    device: torch.device,
    max_samples: int,
) -> np.ndarray:
    """Collect flattened DDIM-inverted epsilon coordinates for fitting PCA."""
    model.eval()
    rows = []
    n = 0

    for _peptides, x0_cpu in iter_peptide_batches(
        files=files,
        peptide_col=args.peptide_col,
        split_col=args.split_col,
        split_filter=split_filter,
        chunksize=args.chunksize,
        deduplicate=True,
    ):
        x0 = x0_cpu.to(device)
        eps = model.ddim_invert(x0, inference_steps=args.ddim_steps).reshape(x0.size(0), -1)
        if args.project_inverted_epsilon_to_sphere:
            eps = project_to_radius(eps, model.bo_radius)
        rows.append(eps.detach().cpu().numpy().astype(np.float32))
        n += eps.size(0)
        if max_samples > 0 and n >= max_samples:
            break

    if not rows:
        raise RuntimeError(f"No epsilon coordinates collected for split={split_filter!r}")

    mat = np.concatenate(rows, axis=0)
    if max_samples > 0 and mat.shape[0] > max_samples:
        mat = mat[:max_samples]
    return mat


def fit_pca_whitener(x: np.ndarray, bo_latent_dim: int, eps: float = 1e-6) -> Dict[str, np.ndarray]:
    """Fit PCA/whitening on training epsilon only."""
    if x.ndim != 2:
        raise ValueError(f"Expected 2D matrix, got {x.shape}")
    n, d = x.shape
    k = min(int(bo_latent_dim), d, max(1, n - 1))
    mean = x.mean(axis=0, keepdims=True)
    xc = x - mean

    # Compact SVD. Components are rows [k, d].
    _, s, vt = np.linalg.svd(xc, full_matrices=False)
    components = vt[:k].astype(np.float32)
    scores = xc @ components.T
    score_std = scores.std(axis=0, keepdims=True).astype(np.float32)
    score_std = np.maximum(score_std, eps)

    explained = (s ** 2) / max(1, n - 1)
    total = float(explained.sum()) if explained.size else 0.0
    evr = explained[:k] / max(total, eps)

    return {
        "mean": mean.astype(np.float32),
        "components": components,
        "score_std": score_std,
        "explained_variance_ratio": evr.astype(np.float32),
    }


def pca_project(epsilon_flat: np.ndarray, pca: Dict[str, np.ndarray]) -> np.ndarray:
    return ((epsilon_flat - pca["mean"]) @ pca["components"].T) / pca["score_std"]


def pca_inverse(z_bo: np.ndarray, pca: Dict[str, np.ndarray]) -> np.ndarray:
    return (z_bo * pca["score_std"]) @ pca["components"] + pca["mean"]


def geometry_diagnostics_np(x: np.ndarray, eps: float = 1e-8) -> Dict[str, float]:
    if x.ndim != 2 or x.shape[0] < 2:
        return {
            "effective_dim_pr": float("nan"),
            "pc1_variance_fraction": float("nan"),
            "pcs90": float("nan"),
            "pcs95": float("nan"),
            "mean_abs_offdiag_corr": float("nan"),
            "max_abs_offdiag_corr": float("nan"),
        }
    xc = x.astype(np.float64) - x.astype(np.float64).mean(axis=0, keepdims=True)
    cov = (xc.T @ xc) / max(1, x.shape[0] - 1)
    eig = np.linalg.eigvalsh(cov).clip(min=0.0)
    total = max(float(eig.sum()), eps)
    pr = total * total / max(float((eig ** 2).sum()), eps)
    eig_desc = eig[::-1]
    frac = eig_desc / total
    cum = np.cumsum(frac)

    z = xc / np.maximum(xc.std(axis=0, keepdims=True), eps)
    corr = (z.T @ z) / float(z.shape[0])
    off = corr - np.diag(np.diag(corr))
    denom = max(1, z.shape[1] * (z.shape[1] - 1))

    return {
        "effective_dim_pr": float(pr),
        "pc1_variance_fraction": float(frac[0]),
        "pcs90": float(np.searchsorted(cum, 0.90) + 1),
        "pcs95": float(np.searchsorted(cum, 0.95) + 1),
        "mean_abs_offdiag_corr": float(np.abs(off).sum() / denom),
        "max_abs_offdiag_corr": float(np.abs(off).max()),
    }


@torch.no_grad()
def build_and_export_bo_coordinates(
    model: DirectSequenceDiffusion,
    files: List[str],
    args: argparse.Namespace,
    device: torch.device,
    checkpoint_label: str,
) -> Dict[str, object]:
    """Fit train-only PCA-whitened BO coordinates and export split-labeled CSV."""
    if not args.export_bo_coordinates:
        return {}

    print("[BO-EXPORT] Collecting training DDIM-inverted epsilon for PCA/whitening...")
    train_eps = collect_inverted_epsilon_matrix(
        model=model,
        files=files,
        args=args,
        split_filter=args.train_split,
        device=device,
        max_samples=args.bo_pca_fit_max_samples,
    )
    pca = fit_pca_whitener(train_eps, args.bo_latent_dim)

    pca_path = os.path.join(args.out_dir, "direct_diffusion_bo_pca_whitener.npz")
    np.savez(
        pca_path,
        mean=pca["mean"],
        components=pca["components"],
        score_std=pca["score_std"],
        explained_variance_ratio=pca["explained_variance_ratio"],
    )

    explained_cum = float(pca["explained_variance_ratio"].sum())
    train_z = pca_project(train_eps, pca)
    geom = geometry_diagnostics_np(train_z)

    out_csv = os.path.join(args.out_dir, "direct_diffusion_pca_bo_coordinates.csv")
    rows: List[Dict[str, object]] = []
    total = 0

    for split_name in [args.train_split, args.validation_split, args.test_split]:
        split_written = 0
        split_cap = int(args.bo_export_max_per_split)
        for peptides, x0_cpu in iter_peptide_batches(
            files=files,
            peptide_col=args.peptide_col,
            split_col=args.split_col,
            split_filter=split_name,
            chunksize=args.chunksize,
            deduplicate=True,
        ):
            x0 = x0_cpu.to(device)
            eps = model.ddim_invert(x0, inference_steps=args.ddim_steps).reshape(x0.size(0), -1)
            if args.project_inverted_epsilon_to_sphere:
                eps = project_to_radius(eps, model.bo_radius)

            eps_np = eps.detach().cpu().numpy().astype(np.float32)
            z_bo = pca_project(eps_np, pca).astype(np.float32)
            eps_back_np = pca_inverse(z_bo, pca).astype(np.float32)
            eps_back = torch.tensor(eps_back_np, dtype=torch.float32, device=device)
            if args.project_generated_epsilon_to_sphere:
                eps_back = project_to_radius(eps_back, model.bo_radius)

            x0_back = model.ddim_sample(eps_back, inference_steps=args.ddim_steps)
            decoded = decode_tensor_to_peptides(x0_back)
            source = peptides

            x_l2 = torch.linalg.norm(
                x0.reshape(x0.size(0), -1) - x0_back.reshape(x0.size(0), -1),
                dim=-1,
            ).detach().cpu().numpy()

            for i, pep in enumerate(source):
                if split_cap > 0 and split_written >= split_cap:
                    break
                row: Dict[str, object] = {
                    "peptide": pep,
                    "peptide_len10": pep,
                    "split": split_name,
                    "decoded_from_bo_latent": decoded[i],
                    "source_to_decoded_edit": levenshtein_edit_distance(pep, decoded[i]),
                    "ddim_x0_l2": float(x_l2[i]),
                    "epsilon_norm": float(np.linalg.norm(eps_np[i])),
                    "bo_latent_norm": float(np.linalg.norm(z_bo[i])),
                }
                for j in range(z_bo.shape[1]):
                    row[f"z_bo_{j:02d}"] = float(z_bo[i, j])
                if args.export_raw_epsilon_columns:
                    for j in range(eps_np.shape[1]):
                        row[f"epsilon_{j:03d}"] = float(eps_np[i, j])
                rows.append(row)
                split_written += 1
                total += 1

            if split_cap > 0 and split_written >= split_cap:
                break

    pd.DataFrame(rows).to_csv(out_csv, index=False)

    meta = {
        "checkpoint_label": checkpoint_label,
        "bo_coordinate_space": "pca_whitened_ddim_inverted_direct_sequence_diffusion_epsilon",
        "raw_epsilon_dim": int(model.bo_dim),
        "bo_latent_dim": int(pca["components"].shape[0]),
        "bo_pca_fit_split": args.train_split,
        "bo_pca_fit_n": int(train_eps.shape[0]),
        "bo_pca_explained_variance_fraction": explained_cum,
        "project_inverted_epsilon_to_sphere": bool(args.project_inverted_epsilon_to_sphere),
        "project_generated_epsilon_to_sphere": bool(args.project_generated_epsilon_to_sphere),
        "pca_path": pca_path,
        "coordinate_csv": out_csv,
        "n_exported_rows": int(total),
        "train_z_geometry": geom,
    }
    with open(os.path.join(args.out_dir, "direct_diffusion_bo_coordinate_export.json"), "w", encoding="utf-8") as f:
        json.dump(meta, f, indent=2)
    print("[BO-EXPORT] Saved:", out_csv)
    print("[BO-EXPORT] Metadata:", meta)
    return meta



