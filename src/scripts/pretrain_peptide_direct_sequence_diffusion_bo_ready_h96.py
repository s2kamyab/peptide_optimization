def make_split_loader(
    files: List[str],
    args: argparse.Namespace,
    split_filter: Optional[str],
    shuffle_files: bool,
) -> DataLoader:
    dataset = PeptideCSVIterable(
        files,
        peptide_col=args.peptide_col,
        split_col=args.split_col,
        split_filter=split_filter,
        chunksize=args.chunksize,
        shuffle_files=shuffle_files,
        deduplicate_within_epoch=args.deduplicate,
    )
    return DataLoader(dataset, batch_size=None, num_workers=0)


def train(args: argparse.Namespace) -> str:
    set_seed(args.seed)
    device = torch.device(args.device)

    cfg = SequenceDiffusionConfig(
        hidden_size=args.hidden_size,
        n_layers=args.n_layers,
        dropout=args.dropout,
        time_dim=args.time_dim,
        train_steps=args.diffusion_train_steps,
        beta_start=args.diffusion_beta_start,
        beta_end=args.diffusion_beta_end,
    )

    files = find_pretrain_files(
        parts_dir=args.parts_dir,
        part_glob=args.part_glob,
        manifest_csv=args.manifest_csv,
        expected_parts=args.expected_parts,
    )

    train_loader = make_split_loader(files, args, args.train_split, shuffle_files=True)
    val_loader = make_split_loader(files, args, args.validation_split, shuffle_files=False)
    test_loader = make_split_loader(files, args, args.test_split, shuffle_files=False)

    os.makedirs(args.out_dir, exist_ok=True)
    history_path = os.path.join(args.out_dir, "pretraining_history_direct_sequence_diffusion.csv")
    checkpoint_path = os.path.join(args.out_dir, f"pretrained_direct_sequence_diffusion_bo_ready_h{cfg.hidden_size}.pt")
    best_val_path = os.path.join(args.out_dir, f"best_validation_direct_sequence_diffusion_bo_ready_h{cfg.hidden_size}.pt")
    final_test_json_path = os.path.join(args.out_dir, "final_test_metrics_direct_sequence_diffusion.json")

    if args.no_resume and os.path.exists(history_path) and not args.append_history:
        os.remove(history_path)

    model = DirectSequenceDiffusion(cfg).to(device)
    optimizer = torch.optim.AdamW(
        model.parameters(),
        lr=args.diffusion_lr,
        weight_decay=args.weight_decay,
    )

    print("DEVICE:", device)
    print("Corrected chain-mapped CSV shards:", len(files))
    print("First part:", files[0])
    print("Last part:", files[-1])
    print("Split column:", args.split_col)
    print("Train/validation/test split names:", args.train_split, args.validation_split, args.test_split)
    print("Direct sequence diffusion config:", asdict(cfg))
    print("BO coordinate shape:", [SEQ_LEN, VOCAB])
    print("BO coordinate dimension:", model.bo_dim)
    print("Recommended BO radius:", model.bo_radius)
    print("No GRU-VAE, no KL, no encoder posterior, no normalizing flow.")
    print("BO latent coordinate:", f"PCA-whitened DDIM epsilon, dim={args.bo_latent_dim}, raw_dim={model.bo_dim}")

    best_val_loss = float("inf")
    best_val_epoch = -1

    for epoch in range(1, args.diffusion_epochs + 1):
        model.train()
        sums = {
            "loss": 0.0,
            "epsilon_mse": 0.0,
            "recon_ce": 0.0,
            "x0_mse": 0.0,
            "token_acc": 0.0,
        }
        n_batches = 0

        for x0 in train_loader:
            x0 = x0.to(device)
            optimizer.zero_grad(set_to_none=True)
            loss, metrics = model.training_loss(
                x0,
                recon_ce_weight=args.recon_ce_weight,
                x0_mse_weight=args.x0_mse_weight,
            )
            loss.backward()
            nn.utils.clip_grad_norm_(model.parameters(), args.grad_clip)
            optimizer.step()

            n_batches += 1
            for key in sums:
                sums[key] += metrics[key]

            if args.log_every and n_batches % args.log_every == 0:
                avg = {k: v / n_batches for k, v in sums.items()}
                print(
                    f"[DIRECT-DIFF][train] epoch={epoch} batch={n_batches} "
                    f"loss={avg['loss']:.4f} eps_mse={avg['epsilon_mse']:.4f} "
                    f"ce={avg['recon_ce']:.4f} x0_mse={avg['x0_mse']:.4f} "
                    f"acc={avg['token_acc']:.4f}"
                )

        train_metrics = {k: v / max(1, n_batches) for k, v in sums.items()}
        train_metrics["n_batches"] = float(n_batches)

        val_metrics = evaluate_split(
            model=model,
            loader=val_loader,
            device=device,
            recon_ce_weight=args.recon_ce_weight,
            x0_mse_weight=args.x0_mse_weight,
            max_batches=args.validation_batches,
        )

        row: Dict[str, float] = {
            "timestamp": datetime.now().isoformat(timespec="seconds"),
            "stage": "direct_sequence_diffusion_chain_mapped_parts",
            "epoch": epoch,
            "diffusion_lr": optimizer.param_groups[0]["lr"],
            "train_steps": cfg.train_steps,
            "hidden_size": cfg.hidden_size,
            "n_layers": cfg.n_layers,
            "time_dim": cfg.time_dim,
            "bo_coordinate_dim": model.bo_dim,
            "bo_radius": model.bo_radius,
            "n_part_files": float(len(files)),
        }
        for k, v in train_metrics.items():
            row[f"train_{k}"] = v
        for k, v in val_metrics.items():
            row[f"validation_{k}"] = v

        append_training_history_csv(history_path, row)

        # Save last epoch checkpoint every epoch.
        save_direct_diffusion_checkpoint(
            checkpoint_path,
            model=model,
            optimizer=optimizer,
            cfg=cfg,
            args=args,
            epoch=epoch,
            metrics={
                **{f"train_{k}": v for k, v in train_metrics.items()},
                **{f"validation_{k}": v for k, v in val_metrics.items()},
            },
        )

        # Save best validation checkpoint.
        if val_metrics["loss"] <= best_val_loss:
            best_val_loss = val_metrics["loss"]
            best_val_epoch = epoch
            save_direct_diffusion_checkpoint(
                best_val_path,
                model=model,
                optimizer=optimizer,
                cfg=cfg,
                args=args,
                epoch=epoch,
                metrics={
                    **{f"train_{k}": v for k, v in train_metrics.items()},
                    **{f"validation_{k}": v for k, v in val_metrics.items()},
                    "checkpoint_selection": "minimum_validation_loss",
                },
            )

        print(f"[DIRECT-DIFF] epoch={epoch} train={train_metrics} validation={val_metrics}")
        print(f"[DIRECT-DIFF] best_validation_loss={best_val_loss:.6f} at epoch={best_val_epoch}")

    # Final test evaluation is run once after training to avoid repeatedly scanning all test shards.
    test_metrics = evaluate_split(
        model=model,
        loader=test_loader,
        device=device,
        recon_ce_weight=args.recon_ce_weight,
        x0_mse_weight=args.x0_mse_weight,
        max_batches=args.test_batches,
    )
    with open(final_test_json_path, "w", encoding="utf-8") as f:
        json.dump(test_metrics, f, indent=2)

    sanity_metrics = run_generation_sanity_check(
        model=model,
        device=device,
        ddim_steps=args.ddim_steps,
        n_samples=args.sanity_samples,
    )
    sanity_path = os.path.join(args.out_dir, "direct_sequence_diffusion_generation_sanity.json")
    with open(sanity_path, "w", encoding="utf-8") as f:
        json.dump(sanity_metrics, f, indent=2)

    # Reconstruction sanity on validation split, because it is not used for optimizer steps.
    recon_loader = make_split_loader(files, args, args.validation_split, shuffle_files=False)
    recon_metrics = run_reconstruction_sanity_check(
        model=model,
        loader=recon_loader,
        device=device,
        n_batches=args.reconstruction_sanity_batches,
    )
    recon_path = os.path.join(args.out_dir, "direct_sequence_diffusion_reconstruction_sanity_validation.json")
    with open(recon_path, "w", encoding="utf-8") as f:
        json.dump(recon_metrics, f, indent=2)

    bo_export_metrics = build_and_export_bo_coordinates(
        model=model,
        files=files,
        args=args,
        device=device,
        checkpoint_label=f"epoch_{args.diffusion_epochs}",
    )

    print("Saved last checkpoint:", checkpoint_path)
    print("Saved best validation checkpoint:", best_val_path)
    print("Saved training history:", history_path)
    print("Saved final test metrics:", final_test_json_path)
    print("Saved generation sanity:", sanity_path)
    print("Saved validation reconstruction sanity:", recon_path)
    print("Final test metrics:", test_metrics)
    print("Generation sanity:", sanity_metrics)
    print("Validation reconstruction sanity:", recon_metrics)

    return checkpoint_path


