def set_seed(seed: int) -> None:
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)


def clean_peptide(x: object) -> Optional[str]:
    pep = str(x).strip().upper()
    if len(pep) != SEQ_LEN:
        return None
    if any(ch not in AA_TO_I for ch in pep):
        return None
    return pep


def onehot_encode_peptides(peptides: List[str]) -> torch.Tensor:
    x = torch.zeros((len(peptides), SEQ_LEN, VOCAB), dtype=torch.float32)
    for n, pep in enumerate(peptides):
        pep = str(pep).strip().upper()
        if len(pep) != SEQ_LEN:
            raise ValueError(f"Expected length {SEQ_LEN}, got {len(pep)} for {pep!r}")
        for t, aa in enumerate(pep):
            if aa not in AA_TO_I:
                raise ValueError(f"Unsupported amino acid {aa!r} in {pep!r}")
            x[n, t, AA_TO_I[aa]] = 1.0
    return x


def decode_tensor_to_peptides(x: torch.Tensor) -> List[str]:
    """Decode [B, 10, 20] scores/continuous one-hot estimates by argmax."""
    idx = x.argmax(dim=-1).detach().cpu().tolist()
    return ["".join(I_TO_AA[int(i)] for i in row) for row in idx]


def levenshtein_edit_distance(a: str, b: str) -> int:
    """Edit-distance diagnostic for source peptide -> decoded peptide roundtrips."""
    if a == b:
        return 0
    previous = list(range(len(b) + 1))
    for i, ca in enumerate(a, start=1):
        current = [i]
        for j, cb in enumerate(b, start=1):
            current.append(
                min(
                    current[j - 1] + 1,
                    previous[j] + 1,
                    previous[j - 1] + int(ca != cb),
                )
            )
        previous = current
    return int(previous[-1])


def project_to_radius(x: torch.Tensor, radius: float) -> torch.Tensor:
    return x / x.norm(dim=-1, keepdim=True).clamp_min(1e-8) * float(radius)


class PeptideCSVIterable(IterableDataset):
    """Stream peptide_len10 values from many CSV shards using pandas chunks.

    The corrected chain-mapped all-metal parts contain a `split` column
    generated by deterministic group-level hashing. This iterable can filter
    by split without loading the full dataset into memory.
    """

    def __init__(
        self,
        files: List[str],
        peptide_col: str = "peptide_len10",
        split_col: str = "split",
        split_filter: Optional[str] = None,
        chunksize: int = 8192,
        shuffle_files: bool = True,
        deduplicate_within_epoch: bool = False,
    ):
        self.files = list(files)
        self.peptide_col = peptide_col
        self.split_col = split_col
        self.split_filter = split_filter
        self.chunksize = int(chunksize)
        self.shuffle_files = bool(shuffle_files)
        self.deduplicate_within_epoch = bool(deduplicate_within_epoch)

    def __iter__(self) -> Iterable[torch.Tensor]:
        files = list(self.files)
        if self.shuffle_files:
            random.shuffle(files)

        usecols = [self.peptide_col]
        if self.split_filter is not None:
            usecols.append(self.split_col)

        seen = set()
        for csv_path in files:
            try:
                reader = pd.read_csv(csv_path, usecols=usecols, chunksize=self.chunksize)
            except ValueError as exc:
                raise ValueError(
                    f"Could not read required columns {usecols} from {csv_path}. "
                    "For train/validation/test filtering, make sure the part CSVs contain a split column."
                ) from exc

            for chunk in reader:
                if self.split_filter is not None:
                    mask = chunk[self.split_col].astype(str).str.lower().eq(str(self.split_filter).lower())
                    chunk = chunk.loc[mask]
                    if chunk.empty:
                        continue

                peptides = []
                for value in chunk[self.peptide_col].tolist():
                    pep = clean_peptide(value)
                    if pep is None:
                        continue
                    if self.deduplicate_within_epoch and pep in seen:
                        continue
                    seen.add(pep)
                    peptides.append(pep)
                if peptides:
                    yield onehot_encode_peptides(peptides)


def _resolve_part_path(path_value: object, manifest_dir: str) -> str:
    """Resolve part paths from the manifest, including Windows-style paths."""
    raw = str(path_value).strip().strip('"').strip("'")
    raw = raw.replace("\\", os.sep)
    raw = raw.replace("\\", os.sep)
    if os.path.isabs(raw) and os.path.exists(raw):
        return raw
    if os.path.exists(raw):
        return raw
    candidate = os.path.join(manifest_dir, raw)
    if os.path.exists(candidate):
        return candidate
    candidate2 = os.path.join(manifest_dir, os.path.basename(raw))
    if os.path.exists(candidate2):
        return candidate2
    candidate3 = os.path.join(manifest_dir, "parts", os.path.basename(raw))
    if os.path.exists(candidate3):
        return candidate3
    return raw


def find_pretrain_files(
    parts_dir: str,
    part_glob: str = "metalpdb_ALL_chain_mapped_len10_high_confidence_part_*.csv",
    manifest_csv: Optional[str] = None,
    expected_parts: Optional[int] = None,
) -> List[str]:
    """Find corrected chain-mapped chunked part files.

    Default pattern matches:
    metalpdb_all_metals_chain_mapped_len10_high_confidence_parts/parts/
    metalpdb_ALL_chain_mapped_len10_high_confidence_part_XXXXXX.csv
    """
    if manifest_csv:
        manifest_csv = str(manifest_csv)
        manifest_dir = os.path.dirname(manifest_csv) or "."
        manifest = pd.read_csv(manifest_csv)
        if "window_csv" not in manifest.columns:
            raise ValueError(f"Manifest {manifest_csv} must contain a window_csv column.")
        files = [_resolve_part_path(p, manifest_dir) for p in manifest["window_csv"].tolist()]
    else:
        pattern = os.path.join(parts_dir, part_glob)
        files = sorted(glob.glob(pattern))

    files = [p for p in files if p and os.path.exists(p) and "failures" not in os.path.basename(p)]
    files = sorted(files)

    if not files:
        searched = manifest_csv if manifest_csv else os.path.join(parts_dir, part_glob)
        raise FileNotFoundError(f"No pretraining part files found from: {searched}")

    if expected_parts is not None and int(expected_parts) > 0 and len(files) != int(expected_parts):
        raise ValueError(
            f"Expected {expected_parts} part files, but found {len(files)}. "
            f"First files: {files[:3]} Last files: {files[-3:]}"
        )

    return files


