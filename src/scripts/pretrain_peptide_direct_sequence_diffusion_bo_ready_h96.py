@torch.no_grad()
def run_generation_sanity_check(
    model: DirectSequenceDiffusion,
    device: torch.device,
    ddim_steps: int,
    n_samples: int,
) -> Dict[str, object]:
    model.eval()
    epsilon = torch.randn(n_samples, model.bo_dim, device=device)
    epsilon = epsilon / epsilon.norm(dim=-1, keepdim=True).clamp(min=1e-8) * model.bo_radius
    x0_hat = model.ddim_sample(epsilon, inference_steps=ddim_steps)
    peptides = decode_tensor_to_peptides(x0_hat)

    counts: Dict[str, int] = {}
    for pep in peptides:
        counts[pep] = counts.get(pep, 0) + 1

    return {
        "n_samples": int(n_samples),
        "unique_fraction": float(len(set(peptides)) / max(len(peptides), 1)),
        "dominant_fraction": float(max(counts.values()) / max(len(peptides), 1)) if counts else float("nan"),
        "base_radius_mean": float(epsilon.norm(dim=-1).mean().item()),
        "raw_epsilon_dim": int(model.bo_dim),
        "bo_coordinate_dim": int(getattr(args, "bo_latent_dim", model.bo_dim)),
        "recommended_bo_radius": float(model.bo_radius),
        "first_20_peptides": peptides[:20],
    }


@torch.no_grad()
def run_reconstruction_sanity_check(
    model: DirectSequenceDiffusion,
    loader: DataLoader,
    device: torch.device,
    n_batches: int,
) -> Dict[str, float]:
    """A simple denoising-reconstruction diagnostic at random timesteps."""
    model.eval()
    sums = {"epsilon_mse": 0.0, "recon_ce": 0.0, "token_acc": 0.0}
    count = 0

    for x0 in loader:
        x0 = x0.to(device)
        batch_size = x0.size(0)
        t = torch.randint(0, model.cfg.train_steps, (batch_size,), device=device)
        noise = torch.randn_like(x0)
        x_t = model.q_sample(x0, t, noise)
        out = model.denoiser(x_t, t)
        predicted_noise = out["predicted_noise"]
        logits = out["x0_logits"]
        target = x0.argmax(dim=-1)
        sums["epsilon_mse"] += float(F.mse_loss(predicted_noise, noise).detach().cpu())
        sums["recon_ce"] += float(F.cross_entropy(logits.reshape(-1, VOCAB), target.reshape(-1)).detach().cpu())
        sums["token_acc"] += float((logits.argmax(dim=-1) == target).float().mean().detach().cpu())
        count += 1
        if count >= n_batches:
            break

    return {k: v / max(count, 1) for k, v in sums.items()}



