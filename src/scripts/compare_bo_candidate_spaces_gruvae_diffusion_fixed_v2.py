from __future__ import annotations

"""
Compare candidate coordinate spaces for Bayesian optimization of Cu-binding peptides.

Candidate spaces
----------------
1) encoder_mu
   Raw 64-D GRU-VAE encoder mean.

2) encoder_h0
   Training-standardized GRU-VAE encoder mean:
       h0 = (mu - latent_mean) / latent_std

3) diffusion_epsilon
   64-D DDIM-inverted diffusion base-noise coordinates.

4) decoder_mu_back [optional; requires .pt checkpoint]
   Actual 64-D latent passed into the GRU decoder after:
       epsilon -> DDIM sample -> h_back -> unstandardize -> mu_back
   This is a valid generative latent representation, although it is downstream
   of the diffusion map.

5) decoder_initial_hidden [diagnostic only; requires .pt checkpoint]
   128-D initial hidden state generated by z_to_h(mu_back).
   This is NOT recommended as a direct BO search space because an arbitrary
   128-D hidden vector does not have a defined inverse to the decoder latent z.

Important:
The true decoder recurrent input at each position is
    concat(token_embedding(previous_token), z)
and therefore depends on the decoded token trajectory. It is not an independent
continuous generative coordinate. This script deliberately does NOT rank that
teacher-forced/recurrent input tensor as a valid BO space.

The script evaluates each space using four complementary criteria:

A. Geometry / intrinsic dimensionality
B. Local objective smoothness
C. Gaussian-process held-out learnability
D. Offline multi-objective Bayesian optimization with ParEGO on the fixed
   evaluated candidate pool

The offline BO benchmark is a fair *representation comparison*, not a substitute
for a prospective black-box BO experiment.

Objectives are assumed to be maximized:
    chelation_sub
    solubility_sub
    stability_sub
    expression_sub
"""

