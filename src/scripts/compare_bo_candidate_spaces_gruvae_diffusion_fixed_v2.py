def save_gp_plot(all_gp: pd.DataFrame, out_dir: Path):
    means = (
        all_gp[all_gp["objective"] == "__MEAN__"]
        .groupby(["space", "train_size"], as_index=False)["rmse"]
        .mean()
    )
    fig, ax = plt.subplots(figsize=(9, 6))
    for space, g in means.groupby("space"):
        ax.plot(g["train_size"], g["rmse"], marker="o", label=space)
    ax.set_xlabel("GP training size")
    ax.set_ylabel("Mean held-out objective RMSE")
    ax.set_title("GP learnability by candidate BO space")
    ax.grid(True, alpha=0.25)
    ax.legend()
    fig.tight_layout()
    fig.savefig(out_dir / "gp_rmse_vs_training_size.png", dpi=300)
    plt.close(fig)


def save_bo_plot(all_bo: pd.DataFrame, out_dir: Path):
    means = (
        all_bo.groupby(["space", "n_evaluated"], as_index=False)["hypervolume"]
        .mean()
    )
    fig, ax = plt.subplots(figsize=(9, 6))
    for space, g in means.groupby("space"):
        ax.plot(g["n_evaluated"], g["hypervolume"], label=space)
    ax.set_xlabel("Number of objective evaluations")
    ax.set_ylabel("Monte Carlo hypervolume")
    ax.set_title("Offline ParEGO sample efficiency by candidate space")
    ax.grid(True, alpha=0.25)
    ax.legend()
    fig.tight_layout()
    fig.savefig(out_dir / "offline_parego_hypervolume.png", dpi=300)
    plt.close(fig)


def main():
    p = argparse.ArgumentParser(
        description="Compare GRU-VAE and diffusion coordinate spaces for peptide BO."
    )
    p.add_argument("--coordinate-csv", required=True)
    p.add_argument(
        "--objective-cols",
        nargs="+",
        default=DEFAULT_OBJECTIVES,
    )
    p.add_argument("--out-dir", default="bo_space_comparison")

    # Optional derivation of decoder-side spaces.
    p.add_argument(
        "--checkpoint",
        default="",
        help="Optional real .pt best-inversion checkpoint, not the .json sidecar.",
    )
    p.add_argument(
        "--finetune-script",
        default="",
        help="Fine-tuning .py defining GRUVAE and LatentDiffusion.",
    )
    p.add_argument("--device", default="cuda" if torch.cuda.is_available() else "cpu")
    p.add_argument("--batch-size", type=int, default=256)

    # Geometry/locality.
    p.add_argument("--knn-k", type=int, default=5)
    p.add_argument("--pair-sample", type=int, default=30000)

    # GP held-out validation.
    p.add_argument(
        "--gp-train-sizes",
        type=int,
        nargs="+",
        default=[64, 128, 256, 512, 1024],
    )
    p.add_argument("--gp-test-fraction", type=float, default=0.20)
    p.add_argument(
        "--gp-seeds",
        type=int,
        nargs="+",
        default=[11, 22, 33],
    )

    # Offline ParEGO benchmark.
    p.add_argument("--skip-offline-bo", action="store_true")
    p.add_argument("--bo-init-size", type=int, default=32)
    p.add_argument("--bo-budget", type=int, default=100)
    p.add_argument(
        "--bo-seeds",
        type=int,
        nargs="+",
        default=[101, 202, 303],
    )
    p.add_argument("--hv-mc-samples", type=int, default=30000)

    p.add_argument("--seed", type=int, default=0)
    args = p.parse_args()

    set_seed(args.seed)

    # The GP optimizer often drives the learned observation-noise term to the
    # lower bound for these nearly deterministic objective labels. That is not
    # a failure; suppress the repetitive sklearn warning so the comparison log
    # remains readable.
    warnings.filterwarnings(
        "ignore",
        category=ConvergenceWarning,
        message=r".*noise_level.*lower bound.*",
    )

    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    df = pd.read_csv(args.coordinate_csv)
    missing_obj = [c for c in args.objective_cols if c not in df.columns]
    if missing_obj:
        raise ValueError(f"Missing objective columns: {missing_obj}")

    Y = df[args.objective_cols].to_numpy(dtype=np.float64)
    spaces = load_direct_spaces(df)

    if args.checkpoint or args.finetune_script:
        if not (args.checkpoint and args.finetune_script):
            raise ValueError(
                "To derive decoder-side spaces, supply BOTH --checkpoint and --finetune-script."
            )
        spaces.update(
            derive_decoder_spaces(
                df=df,
                checkpoint_path=args.checkpoint,
                finetune_script=args.finetune_script,
                device=torch.device(args.device),
                batch_size=args.batch_size,
            )
        )

    if not spaces:
        raise ValueError("No candidate spaces could be loaded.")

    # Sanity checks: the three core latent coordinate systems are all expected
    # to have exactly latent_dim=64 for the current H64/Z64 model.
    expected_dim = 64
    for core_name in ["encoder_mu", "encoder_h0", "diffusion_epsilon"]:
        if core_name in spaces and spaces[core_name].shape[1] != expected_dim:
            raise ValueError(
                f"{core_name} has {spaces[core_name].shape[1]} columns, "
                f"but expected {expected_dim}. Check coordinate-column parsing."
            )

    # Same finite rows across all spaces for a fair comparison.
    common = np.isfinite(Y).all(axis=1)
    for X in spaces.values():
        common &= np.isfinite(X).all(axis=1)

    Y = Y[common]
    df = df.loc[common].reset_index(drop=True)
    spaces = {k: v[common] for k, v in spaces.items()}

    print(f"Rows used in fair comparison: {len(Y)}")
    print(f"Spaces: {[(k, v.shape) for k, v in spaces.items()]}")

    all_gp = []
    all_bo = []
    summaries = []

    # decoder_initial_hidden is a derived diagnostic representation, not a
    # directly invertible optimization coordinate.
    ineligible = {"decoder_initial_hidden"}

    for space_name, X in spaces.items():
        print(f"\n=== {space_name} shape={X.shape} ===")

        geom = geometry_metrics(X)
        local = local_objective_metrics(
            X, Y,
            k=args.knn_k,
            pair_sample=args.pair_sample,
            seed=args.seed,
        )

        gp = gp_learnability(
            X=X,
            Y=Y,
            objective_names=args.objective_cols,
            train_sizes=args.gp_train_sizes,
            test_fraction=args.gp_test_fraction,
            seeds=args.gp_seeds,
        )
        gp.insert(0, "space", space_name)
        all_gp.append(gp)

        max_gp_size = int(gp["train_size"].max())
        gp_summary = aggregate_gp(gp, max_gp_size)

        bo_eligible = space_name not in ineligible

        final_hv = np.nan
        hv_auc = np.nan
        if not args.skip_offline_bo and bo_eligible:
            bo = parego_offline_bo(
                X=X,
                Y=Y,
                init_size=args.bo_init_size,
                budget=args.bo_budget,
                seeds=args.bo_seeds,
                hv_mc_samples=args.hv_mc_samples,
            )
            bo.insert(0, "space", space_name)
            all_bo.append(bo)

            final_rows = bo[bo["n_evaluated"] == bo["n_evaluated"].max()]
            final_hv = float(final_rows["hypervolume"].mean())

            # Mean hypervolume AUC across seeds.
            aucs = []
            for seed, g in bo.groupby("seed"):
                g = g.sort_values("n_evaluated")
                aucs.append(np.trapezoid(g["hypervolume"], g["n_evaluated"]))
            hv_auc = float(np.mean(aucs))

        summaries.append({
            "space": space_name,
            "bo_eligible": bo_eligible,
            **geom,
            **local,
            **gp_summary,
            "final_hypervolume": final_hv,
            "hypervolume_auc": hv_auc,
        })

    gp_all = pd.concat(all_gp, ignore_index=True)
    gp_all.to_csv(out_dir / "gp_learnability_all_spaces.csv", index=False)

    if all_bo:
        bo_all = pd.concat(all_bo, ignore_index=True)
        bo_all.to_csv(out_dir / "offline_parego_all_spaces.csv", index=False)
        save_bo_plot(bo_all, out_dir)

    summary = pd.DataFrame(summaries)
    ranked = rank_spaces(summary)
    ranked.to_csv(out_dir / "bo_space_comparison_summary_ranked.csv", index=False)

    save_gp_plot(gp_all, out_dir)

    # Human-readable recommendation.
    eligible_ranked = ranked[ranked["bo_eligible"]].sort_values("mean_rank")
    best = eligible_ranked.iloc[0]

    lines = []
    lines.append("BAYESIAN-OPTIMIZATION CANDIDATE-SPACE COMPARISON")
    lines.append("=" * 88)
    lines.append(f"n_rows={len(Y)}")
    lines.append(f"objectives={args.objective_cols}")
    lines.append("")
    lines.append("RANKED SUMMARY")
    lines.append("-" * 88)

    show_cols = [
        "space",
        "dimension",
        "effective_dimension_participation_ratio",
        "pca_components_95pct",
        "knn_objective_l2_mean",
        "pair_distance_objective_spearman",
        "gp_rmse",
        "gp_r2",
        "gp_spearman",
        "final_hypervolume",
        "hypervolume_auc",
        "mean_rank",
    ]
    lines.append(ranked[show_cols].to_string(index=False))
    lines.append("")
    lines.append(f"TOP ELIGIBLE SPACE BY COMPOSITE RANK: {best['space']}")
    lines.append("")
    lines.append("INTERPRETATION RULES")
    lines.append("-" * 88)
    lines.append("Lower GP RMSE and kNN objective distance are better.")
    lines.append("Higher GP R2, GP Spearman, distance/objective Spearman, hypervolume, and HV-AUC are better.")
    lines.append(
        "encoder_mu and encoder_h0 are related by an affine standardization, so a well-scaled GP may perform similarly."
    )
    lines.append(
        "diffusion_epsilon is preferable only if it improves objective learnability and/or offline BO sample efficiency enough to justify DDIM inversion/sampling error."
    )
    lines.append(
        "decoder_initial_hidden is diagnostic only and is excluded from BO ranking because arbitrary hidden vectors do not map uniquely back to decoder latents."
    )
    lines.append(
        "The recurrent decoder input concat(token_embedding, z) is trajectory-dependent and should not be optimized directly."
    )
    lines.append(
        "Final confirmation should use prospective BO with the same initial design, qEHVI/ParEGO settings, objective-evaluation budget, and random seeds."
    )

    report = "\n".join(lines) + "\n"
    (out_dir / "bo_space_comparison_report.txt").write_text(report, encoding="utf-8")
    print(report)
    print(f"Saved results to: {out_dir.resolve()}")


if __name__ == "__main__":
    main()
