def load_direct_spaces(df: pd.DataFrame) -> Dict[str, np.ndarray]:
    spaces = {}

    mu_cols = sorted_prefixed_columns(df, "mu_")
    h_cols = sorted_prefixed_columns(df, "h0_standardized_")
    eps_cols = sorted_prefixed_columns(df, "epsilon_")

    print(
        "Detected coordinate columns: "
        f"mu={len(mu_cols)}, h0={len(h_cols)}, epsilon={len(eps_cols)}"
    )

    if mu_cols:
        spaces["encoder_mu"] = df[mu_cols].to_numpy(dtype=np.float64)

    if h_cols:
        spaces["encoder_h0"] = df[h_cols].to_numpy(dtype=np.float64)

    if eps_cols:
        spaces["diffusion_epsilon"] = df[eps_cols].to_numpy(dtype=np.float64)

    return spaces


@torch.no_grad()
def derive_decoder_spaces(
    df: pd.DataFrame,
    checkpoint_path: str,
    finetune_script: str,
    device: torch.device,
    batch_size: int,
) -> Dict[str, np.ndarray]:
    """
    Derive actual decoder-side latent coordinates using the selected diffusion checkpoint.

    Requires the real .pt file, not only the .json sidecar.
    """
    module = import_module_py314_safe(
        finetune_script,
        "cu_gruvae_diffusion_module_for_space_comparison",
    )
    ckpt = torch.load(checkpoint_path, map_location=device)

    cfg_dict = ckpt["model_config"]
    diff_dict = ckpt["diffusion_config"]

    cfg = module.ModelConfig(**cfg_dict)
    diff_cfg = module.DiffusionConfig(**diff_dict)

    vae = module.GRUVAE(cfg).to(device)
    diffusion = module.LatentDiffusion(cfg.latent_dim, diff_cfg).to(device)

    vae.load_state_dict(ckpt["vae_state_dict"], strict=True)
    diffusion.load_state_dict(ckpt["diffusion_state_dict"], strict=True)
    vae.eval()
    diffusion.eval()

    latent_mean = ckpt["latent_mean"].to(device).float()
    latent_std = ckpt["latent_std"].to(device).float().clamp_min(1e-6)

    eps_cols = sorted_prefixed_columns(df, "epsilon_")
    if not eps_cols:
        raise ValueError("Coordinate CSV has no epsilon_* columns.")

    eps_all = torch.tensor(
        df[eps_cols].to_numpy(dtype=np.float32),
        device=device,
    )

    ddim_steps = int(ckpt.get("args", {}).get("ddim_steps", 20))

    mu_back_all = []
    hidden_all = []

    for start in range(0, len(df), batch_size):
        eps = eps_all[start:start + batch_size]
        h_back = diffusion.ddim_sample(eps, inference_steps=ddim_steps)
        mu_back = (
            h_back * latent_std.unsqueeze(0)
            + latent_mean.unsqueeze(0)
        )
        initial_hidden = vae.dec.z_to_h(mu_back)

        mu_back_all.append(mu_back.detach().cpu().numpy())
        hidden_all.append(initial_hidden.detach().cpu().numpy())

    return {
        "decoder_mu_back": np.concatenate(mu_back_all, axis=0).astype(np.float64),
        # Diagnostic-only representation.
        "decoder_initial_hidden": np.concatenate(hidden_all, axis=0).astype(np.float64),
    }


