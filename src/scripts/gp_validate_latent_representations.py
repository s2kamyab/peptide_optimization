def set_seed(seed: int) -> None:
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)


def clean_peptide(x: object) -> Optional[str]:
    s = str(x).strip().upper()
    if len(s) != SEQ_LEN:
        return None
    if any(ch not in AA_TO_I for ch in s):
        return None
    return s


def onehot_encode_peptides(peptides: Sequence[str]) -> torch.Tensor:
    x = torch.zeros((len(peptides), SEQ_LEN, VOCAB), dtype=torch.float32)
    for n, pep in enumerate(peptides):
        p = clean_peptide(pep)
        if p is None:
            raise ValueError(f"Invalid peptide: {pep!r}")
        for t, aa in enumerate(p):
            x[n, t, AA_TO_I[aa]] = 1.0
    return x


def rankdata_average(x: np.ndarray) -> np.ndarray:
    return pd.Series(np.asarray(x, dtype=float)).rank(method="average").to_numpy(float)


def spearman_safe(a: np.ndarray, b: np.ndarray) -> float:
    a = np.asarray(a, dtype=float)
    b = np.asarray(b, dtype=float)
    mask = np.isfinite(a) & np.isfinite(b)
    a = a[mask]
    b = b[mask]
    if len(a) < 3:
        return float("nan")
    ra = rankdata_average(a)
    rb = rankdata_average(b)
    if np.std(ra) < 1e-12 or np.std(rb) < 1e-12:
        return float("nan")
    return float(np.corrcoef(ra, rb)[0, 1])


def r2_score_np(y: np.ndarray, pred: np.ndarray) -> float:
    y = np.asarray(y, dtype=float)
    pred = np.asarray(pred, dtype=float)
    ss_res = float(np.sum((y - pred) ** 2))
    ss_tot = float(np.sum((y - np.mean(y)) ** 2))
    if ss_tot < 1e-15:
        return float("nan")
    return 1.0 - ss_res / ss_tot


def normal_z_for_coverage(level: float) -> float:
    # central interval: P(-z <= Z <= z) = level
    p = torch.tensor((1.0 + float(level)) / 2.0, dtype=torch.float64)
    return float(torch.distributions.Normal(0.0, 1.0).icdf(p).item())


def objective_columns_from_details(
    details: pd.DataFrame,
    requested: Sequence[str],
) -> List[str]:
    cols = []
    for c in requested:
        if f"neighbor_{c}" in details.columns:
            cols.append(c)
    if not cols:
        raise ValueError(
            "No requested neighbor objective columns found. Expected columns like "
            "neighbor_chelation_sub in the corrected details CSV."
        )
    return cols


def find_peptide_col(df: pd.DataFrame, preferred: str = "peptide_len10") -> str:
    for c in [preferred, "peptide_len10", "sequence", "peptide"]:
        if c in df.columns:
            return c
    raise ValueError(f"No peptide column found. Available={list(df.columns)}")


