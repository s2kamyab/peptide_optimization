def detect_realnvp_columns(
    df: pd.DataFrame,
    explicit_prefix: str,
) -> List[str]:
    if explicit_prefix:
        cols = [
            c for c in df.columns
            if str(c).startswith(explicit_prefix)
        ]
        if not cols:
            raise ValueError(
                f"No RealNVP columns start with "
                f"{explicit_prefix!r}"
            )
        return sorted(cols)

    prefixes = [
        "zK_",
        "zk_",
        "zK",
        "flow_",
        "postflow_",
        "post_flow_",
        "latent_flow_",
    ]

    candidates = []
    for prefix in prefixes:
        cols = [
            c for c in df.columns
            if str(c).startswith(prefix)
            and pd.api.types.is_numeric_dtype(df[c])
        ]
        if len(cols) >= 2:
            candidates.append((len(cols), prefix, sorted(cols)))

    if not candidates:
        # Last-resort numeric latent-ish columns.
        cols = [
            c for c in df.columns
            if pd.api.types.is_numeric_dtype(df[c])
            and any(
                token in str(c).lower()
                for token in ["zk", "flow"]
            )
        ]
        if len(cols) >= 2:
            return sorted(cols)

        raise ValueError(
            "Could not auto-detect RealNVP post-flow columns. "
            "Pass --realnvp-prefix explicitly."
        )

    candidates.sort(reverse=True)
    return candidates[0][2]


def add_realnvp_representation(
    meta: pd.DataFrame,
    representations: Dict[str, np.ndarray],
    csv_path: str,
    peptide_col_preferred: str,
    prefix: str,
):
    if not csv_path:
        return meta, representations

    rdf = pd.read_csv(csv_path)
    pep_col = find_peptide_col(
        rdf,
        peptide_col_preferred,
    )
    cols = detect_realnvp_columns(
        rdf,
        prefix,
    )

    rdf = rdf.copy()
    rdf["_pep"] = rdf[pep_col].map(clean_peptide)
    rdf = rdf.dropna(subset=["_pep"]).copy()
    rdf = rdf.drop_duplicates(
        "_pep",
        keep="first",
    )

    lookup = {
        p: row[cols].to_numpy(dtype=float)
        for p, (_, row) in zip(
            rdf["_pep"].tolist(),
            rdf.iterrows(),
        )
    }

    keep = np.array(
        [
            p in lookup
            for p in meta["peptide_len10"]
        ],
        dtype=bool,
    )

    n_before = len(meta)
    meta2 = meta.loc[keep].reset_index(drop=True)

    reps2 = {
        name: X[keep]
        for name, X in representations.items()
    }

    X_flow = np.vstack(
        [
            lookup[p]
            for p in meta2["peptide_len10"]
        ]
    ).astype(np.float64)

    reps2["realnvp"] = X_flow

    print(
        f"RealNVP common-point intersection: "
        f"{len(meta2)}/{n_before}; "
        f"flow_dim={X_flow.shape[1]}"
    )

    return meta2, reps2


