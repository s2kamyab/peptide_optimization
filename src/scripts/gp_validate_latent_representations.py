def standardize_X_train_test(
    X_train: np.ndarray,
    X_test: np.ndarray,
) -> Tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    mu = np.mean(X_train, axis=0)
    std = np.std(X_train, axis=0)
    std = np.where(std < 1e-8, 1.0, std)
    return (
        (X_train - mu) / std,
        (X_test - mu) / std,
        mu,
        std,
    )


def build_gp(
    train_X: torch.Tensor,
    train_Y: torch.Tensor,
    kernel: str,
    ard: bool,
) -> SingleTaskGP:
    d = train_X.shape[-1]
    ard_dims = d if ard else None

    if kernel == "rbf":
        base = RBFKernel(
            ard_num_dims=ard_dims,
        )
    else:
        base = MaternKernel(
            nu=2.5,
            ard_num_dims=ard_dims,
        )

    covar = ScaleKernel(base)

    model = SingleTaskGP(
        train_X=train_X,
        train_Y=train_Y,
        covar_module=covar,
        outcome_transform=Standardize(m=1),
    )
    return model


def fit_single_gp(
    X_train: np.ndarray,
    y_train: np.ndarray,
    device: torch.device,
    dtype: torch.dtype,
    kernel: str,
    ard: bool,
    max_fit_attempts: int,
) -> SingleTaskGP:
    train_X = torch.tensor(
        X_train,
        device=device,
        dtype=dtype,
    )
    train_Y = torch.tensor(
        y_train.reshape(-1, 1),
        device=device,
        dtype=dtype,
    )

    last_exc = None

    for attempt in range(max(1, int(max_fit_attempts))):
        try:
            model = build_gp(
                train_X,
                train_Y,
                kernel,
                ard,
            ).to(device=device, dtype=dtype)

            mll = ExactMarginalLogLikelihood(
                model.likelihood,
                model,
            )

            # BoTorch handles the optimizer details and constraints.
            fit_gpytorch_mll(mll)
            model.eval()
            model.likelihood.eval()
            return model

        except Exception as exc:
            last_exc = exc
            warnings.warn(
                f"GP fit attempt {attempt + 1} failed: {exc}"
            )
            if device.type == "cuda":
                torch.cuda.empty_cache()

    raise RuntimeError(
        f"GP fitting failed after {max_fit_attempts} attempts"
    ) from last_exc


@torch.no_grad()
def gp_predict(
    model: SingleTaskGP,
    X_test: np.ndarray,
    device: torch.device,
    dtype: torch.dtype,
) -> Tuple[np.ndarray, np.ndarray]:
    tx = torch.tensor(
        X_test,
        device=device,
        dtype=dtype,
    )

    # observation_noise=True makes NLPD / predictive interval coverage evaluate
    # the predictive distribution for observations, not only latent f(x).
    posterior = model.posterior(
        tx,
        observation_noise=True,
    )

    mean = (
        posterior.mean
        .squeeze(-1)
        .detach()
        .cpu()
        .numpy()
    )
    var = (
        posterior.variance
        .squeeze(-1)
        .clamp(min=1e-12)
        .detach()
        .cpu()
        .numpy()
    )
    return mean, var


def predictive_metrics(
    y: np.ndarray,
    mean: np.ndarray,
    var: np.ndarray,
) -> Dict[str, float]:
    y = np.asarray(y, dtype=float)
    mean = np.asarray(mean, dtype=float)
    var = np.maximum(
        np.asarray(var, dtype=float),
        1e-12,
    )

    err = mean - y
    rmse = float(np.sqrt(np.mean(err ** 2)))
    mae = float(np.mean(np.abs(err)))
    r2 = r2_score_np(y, mean)
    spearman = spearman_safe(y, mean)

    nlpd_each = 0.5 * (
        np.log(2.0 * np.pi * var)
        + ((y - mean) ** 2) / var
    )
    nlpd = float(np.mean(nlpd_each))

    sd = np.sqrt(var)
    zres = (y - mean) / sd

    coverage = {}
    calibration_abs_errors = []
    for level in [0.50, 0.80, 0.90, 0.95]:
        z = normal_z_for_coverage(level)
        inside = np.abs(y - mean) <= z * sd
        cov = float(np.mean(inside))
        coverage[level] = cov
        calibration_abs_errors.append(
            abs(cov - level)
        )

    return {
        "rmse": rmse,
        "mae": mae,
        "r2": r2,
        "spearman": spearman,
        "nlpd": nlpd,
        "coverage_50": coverage[0.50],
        "coverage_80": coverage[0.80],
        "coverage_90": coverage[0.90],
        "coverage_95": coverage[0.95],
        "coverage95_abs_error": abs(
            coverage[0.95] - 0.95
        ),
        "calibration_ece": float(
            np.mean(calibration_abs_errors)
        ),
        "standardized_residual_mean": float(
            np.mean(zres)
        ),
        "standardized_residual_std": float(
            np.std(zres)
        ),
        "mean_predictive_sd": float(
            np.mean(sd)
        ),
    }


