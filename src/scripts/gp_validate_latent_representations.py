from __future__ import annotations

"""
GP surrogate validation benchmark for peptide BO latent representations.

Primary comparison
------------------
1) diffusion_epsilon
   DDIM base-noise coordinates used by epsilon-space BO.

2) vae_h0_ddim
   Standardized VAE latent h produced by deterministic DDIM sampling from each
   epsilon point. This is the continuous latent passed (after unstandardizing)
   to the frozen VAE decoder, so it gives the fairest same-point comparison
   against epsilon for the already black-box-scored epsilon samples.

3) vae_h0_encoded
   Standardized encoder-mu of the decoded peptide itself. This tests the direct
   VAE encoder representation of the same evaluated peptide.

4) realnvp (optional)
   Post-flow coordinates loaded from a separate CSV and matched by peptide.
   Auto-detects common prefixes such as zK_, zk_, flow_, postflow_, etc.

Inputs
------
- The SAME latent-diffusion checkpoint used by the epsilon smoothness test.
- Original Cu black-box-scored CSV used for source-center selection.
- Corrected epsilon neighbor details CSV containing the true four black-box
  objective values for every decoded neighbor peptide.
- Optional corrected decoded-center CSV. Centers are included when their
  objective columns are available.
- Optional RealNVP coordinate CSV.

The script reconstructs the exact epsilon samples generated by
diagnose_epsilon_objective_smoothness_corrected.py using the same center
selection, seed, sigmas, neighbor count, sphere projection and DDIM steps.

Metrics per objective
---------------------
- RMSE
- MAE
- R^2
- Spearman correlation
- Gaussian negative log predictive density (NLPD)
- uncertainty calibration:
    * empirical 50/80/90/95% predictive interval coverage
    * calibration ECE = mean |coverage - nominal|
    * 95% coverage error
    * standardized residual mean/std
- performance versus training-set size

Evaluation design
-----------------
- SAME train/test groups for every representation.
- Default split is by decoded PEPTIDE, not by row, preventing identical peptide
  leakage when a decoder maps multiple latent points to the same sequence.
- Nested training subsets are reused across representations for fairness.
- Independent exact SingleTaskGP models are fitted per objective.
- Inputs are standardized using TRAINING data only.
- Targets are standardized internally by BoTorch's Standardize outcome transform.

Notes
-----
Exact GPs scale cubically with training size. Start with:
    --train-sizes 64 128 256 512 1024
and increase only if runtime/memory are acceptable.

For a publication-quality representation comparison, use several split seeds,
e.g.:
    --split-seeds 11 22 33 44 55
"""

