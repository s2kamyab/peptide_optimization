def make_grouped_split(
    meta: pd.DataFrame,
    test_fraction: float,
    seed: int,
) -> Tuple[np.ndarray, np.ndarray]:
    rng = np.random.default_rng(seed)

    groups = np.array(
        sorted(
            meta["peptide_len10"]
            .astype(str)
            .unique()
            .tolist()
        )
    )

    rng.shuffle(groups)

    n_test_groups = max(
        1,
        int(round(len(groups) * float(test_fraction))),
    )
    test_groups = set(
        groups[:n_test_groups].tolist()
    )

    test_mask = (
        meta["peptide_len10"]
        .astype(str)
        .isin(test_groups)
        .to_numpy()
    )

    test_idx = np.flatnonzero(test_mask)
    train_idx = np.flatnonzero(~test_mask)

    if len(test_idx) < 2 or len(train_idx) < 4:
        raise ValueError(
            f"Grouped split too small: train={len(train_idx)}, "
            f"test={len(test_idx)}"
        )

    return train_idx, test_idx


def nested_training_indices(
    train_pool_idx: np.ndarray,
    sizes: Sequence[int],
    seed: int,
) -> Dict[int, np.ndarray]:
    rng = np.random.default_rng(seed)
    order = np.asarray(train_pool_idx).copy()
    rng.shuffle(order)

    out = {}
    for requested in sorted(set(int(s) for s in sizes)):
        n = min(requested, len(order))
        if n < 4:
            continue
        out[requested] = order[:n].copy()
    return out


