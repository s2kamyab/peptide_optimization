def load_models(
    checkpoint_path: str,
    device: torch.device,
):
    ckpt = torch.load(checkpoint_path, map_location=device)

    mc = ckpt["model_config"]
    dc = ckpt["diffusion_config"]

    cfg = ModelConfig(
        hidden_size=int(mc["hidden_size"]),
        latent_dim=int(mc["latent_dim"]),
        n_layers=int(mc["n_layers"]),
        dropout=float(mc.get("dropout", 0.0)),
        decoder_conditioning=str(
            mc.get(
                "decoder_conditioning",
                "concat_z_at_every_decoder_step",
            )
        ),
    )

    diff_cfg = DiffusionConfig(
        hidden_dim=int(dc["hidden_dim"]),
        time_dim=int(dc["time_dim"]),
        n_blocks=int(dc["n_blocks"]),
        train_steps=int(dc["train_steps"]),
        beta_start=float(dc["beta_start"]),
        beta_end=float(dc["beta_end"]),
    )

    vae = GRUVAE(cfg).to(device)
    diffusion = LatentDiffusion(cfg.latent_dim, diff_cfg).to(device)

    vae.load_state_dict(
        ckpt["vae_state_dict"],
        strict=True,
    )
    diffusion.load_state_dict(
        ckpt["diffusion_state_dict"],
        strict=True,
    )

    vae.eval()
    diffusion.eval()

    latent_mean = ckpt["latent_mean"].to(device).float()
    latent_std = (
        ckpt["latent_std"]
        .to(device)
        .float()
        .clamp(min=1e-6)
    )

    return ckpt, cfg, vae, diffusion, latent_mean, latent_std


def select_source_centers(
    cu_df: pd.DataFrame,
    peptide_col: str,
    objective_cols: Sequence[str],
    n_centers: int,
    center_selection: str,
    rank_objective: str,
    seed: int,
) -> List[Tuple[int, str]]:
    valid = []
    for idx, row in cu_df.iterrows():
        pep = clean_peptide(row[peptide_col])
        if pep is None:
            continue
        if any(pd.isna(row[c]) for c in objective_cols):
            continue
        valid.append((idx, pep))

    if not valid:
        raise ValueError("No valid source peptides.")

    n_centers = min(int(n_centers), len(valid))
    rng = np.random.default_rng(seed)

    if center_selection == "random":
        ids = rng.choice(
            len(valid),
            size=n_centers,
            replace=False,
        )
        return [valid[int(i)] for i in ids]

    rank_col = (
        rank_objective
        if rank_objective in cu_df.columns
        else objective_cols[0]
    )

    ranked = sorted(
        [
            (
                float(cu_df.loc[idx, rank_col]),
                idx,
                pep,
            )
            for idx, pep in valid
        ],
        reverse=True,
    )
    return [
        (idx, pep)
        for _, idx, pep in ranked[:n_centers]
    ]


@torch.no_grad()
def reconstruct_gp_dataset(
    args: argparse.Namespace,
    objective_cols: Sequence[str],
    device: torch.device,
):
    ckpt, cfg, vae, diffusion, latent_mean, latent_std = load_models(
        args.checkpoint,
        device,
    )

    cu_df = pd.read_csv(args.cu_csv)
    peptide_col = find_peptide_col(
        cu_df,
        args.peptide_col,
    )

    selected = select_source_centers(
        cu_df=cu_df,
        peptide_col=peptide_col,
        objective_cols=objective_cols,
        n_centers=args.n_centers,
        center_selection=args.center_selection,
        rank_objective=args.rank_objective,
        seed=args.sample_seed,
    )

    source_peptides = [pep for _, pep in selected]
    x_centers = onehot_encode_peptides(
        source_peptides
    ).to(device)

    mu, _, _ = vae.enc(x_centers)
    h0_source = standardize_mu(
        mu,
        latent_mean,
        latent_std,
    )

    eps_centers = diffusion.ddim_invert(
        h0_source,
        inference_steps=args.ddim_steps,
    )

    radius = (
        float(args.radius)
        if args.radius is not None
        else math.sqrt(cfg.latent_dim)
    )

    if args.project_centers_to_sphere:
        eps_centers = project_to_radius(
            eps_centers,
            radius,
        )

    h_centers = diffusion.ddim_sample(
        eps_centers,
        inference_steps=args.ddim_steps,
    )

    details = pd.read_csv(
        args.corrected_neighbor_details_csv
    )

    required_id_cols = [
        "center_index",
        "sigma",
        "neighbor_index",
        "neighbor_peptide",
    ]
    missing_id = [
        c for c in required_id_cols
        if c not in details.columns
    ]
    if missing_id:
        raise ValueError(
            f"Corrected details CSV missing columns: {missing_id}"
        )

    # Index rows by deterministic generation identity.
    detail_lookup = {}
    for _, row in details.iterrows():
        key = (
            int(row["center_index"]),
            round(float(row["sigma"]), 12),
            int(row["neighbor_index"]),
        )
        detail_lookup[key] = row

    gen = torch.Generator(device="cpu")
    gen.manual_seed(int(args.sample_seed) + 1234)

    rows = []
    eps_vectors = []
    h_ddim_vectors = []

    for i, src in enumerate(source_peptides):
        eps0 = eps_centers[i : i + 1]

        for sigma in args.sigmas:
            for j in range(args.neighbors_per_sigma):
                noise = (
                    torch.randn(
                        eps0.shape,
                        generator=gen,
                        device="cpu",
                        dtype=torch.float32,
                    )
                    .to(device)
                    * float(sigma)
                )

                eps1 = eps0 + noise
                if args.renormalize_neighbors:
                    eps1 = project_to_radius(
                        eps1,
                        radius,
                    )

                h1 = diffusion.ddim_sample(
                    eps1,
                    inference_steps=args.ddim_steps,
                )

                key = (
                    i,
                    round(float(sigma), 12),
                    j,
                )
                if key not in detail_lookup:
                    raise KeyError(
                        f"No corrected-details row for {key}"
                    )

                drow = detail_lookup[key]
                pep = clean_peptide(
                    drow["neighbor_peptide"]
                )
                if pep is None:
                    raise ValueError(
                        f"Invalid neighbor peptide for {key}: "
                        f"{drow['neighbor_peptide']!r}"
                    )

                y = {}
                for c in objective_cols:
                    col = f"neighbor_{c}"
                    if col not in details.columns:
                        raise ValueError(
                            f"Missing objective column: {col}"
                        )
                    value = float(drow[col])
                    if not np.isfinite(value):
                        raise ValueError(
                            f"Non-finite {col} for {key}"
                        )
                    y[c] = value

                rows.append(
                    {
                        "point_type": "neighbor",
                        "center_index": i,
                        "source_peptide": src,
                        "peptide_len10": pep,
                        "sigma": float(sigma),
                        "neighbor_index": int(j),
                        **y,
                    }
                )
                eps_vectors.append(
                    eps1.squeeze(0).detach().cpu().numpy()
                )
                h_ddim_vectors.append(
                    h1.squeeze(0).detach().cpu().numpy()
                )

    meta = pd.DataFrame(rows)
    X_eps = np.vstack(eps_vectors)
    X_h_ddim = np.vstack(h_ddim_vectors)

    # Direct VAE encoder h0 of the evaluated decoded peptide.
    X_h_encoded = encode_standardized_h0(
        vae,
        meta["peptide_len10"].tolist(),
        latent_mean,
        latent_std,
        device,
        batch_size=args.encode_batch_size,
    )

    # Optional decoded centers.
    if args.include_centers and args.decoded_centers_csv:
        center_df = pd.read_csv(
            args.decoded_centers_csv
        )

        center_rows = []
        center_eps = []
        center_h_ddim = []

        for _, row in center_df.iterrows():
            i = int(row["center_index"])
            pep = clean_peptide(
                row["center_decoded_peptide"]
            )
            if pep is None:
                continue

            y = {}
            complete = True
            for c in objective_cols:
                col = f"center_decoded_{c}"
                if col not in center_df.columns:
                    complete = False
                    break
                value = pd.to_numeric(
                    pd.Series([row[col]]),
                    errors="coerce",
                ).iloc[0]
                if pd.isna(value):
                    complete = False
                    break
                y[c] = float(value)

            if not complete:
                continue

            center_rows.append(
                {
                    "point_type": "center",
                    "center_index": i,
                    "source_peptide": source_peptides[i],
                    "peptide_len10": pep,
                    "sigma": 0.0,
                    "neighbor_index": -1,
                    **y,
                }
            )
            center_eps.append(
                eps_centers[i].detach().cpu().numpy()
            )
            center_h_ddim.append(
                h_centers[i].detach().cpu().numpy()
            )

        if center_rows:
            cmeta = pd.DataFrame(center_rows)
            chenc = encode_standardized_h0(
                vae,
                cmeta["peptide_len10"].tolist(),
                latent_mean,
                latent_std,
                device,
                batch_size=args.encode_batch_size,
            )

            meta = pd.concat(
                [meta, cmeta],
                ignore_index=True,
            )
            X_eps = np.vstack(
                [X_eps, np.vstack(center_eps)]
            )
            X_h_ddim = np.vstack(
                [X_h_ddim, np.vstack(center_h_ddim)]
            )
            X_h_encoded = np.vstack(
                [X_h_encoded, chenc]
            )

    representations = {
        "diffusion_epsilon": X_eps.astype(np.float64),
        "vae_h0_ddim": X_h_ddim.astype(np.float64),
        "vae_h0_encoded": X_h_encoded.astype(np.float64),
    }

    return (
        meta.reset_index(drop=True),
        representations,
        {
            "checkpoint_epoch": ckpt.get("epoch"),
            "checkpoint_selection": ckpt.get(
                "checkpoint_selection"
            ),
            "latent_dim": cfg.latent_dim,
            "radius": radius,
        },
    )


