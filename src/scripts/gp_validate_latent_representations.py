@dataclass
class ModelConfig:
    hidden_size: int = 64
    latent_dim: int = 64
    n_layers: int = 2
    dropout: float = 0.0
    decoder_conditioning: str = "concat_z_at_every_decoder_step"


@dataclass
class DiffusionConfig:
    hidden_dim: int = 128
    time_dim: int = 32
    n_blocks: int = 4
    train_steps: int = 100
    beta_start: float = 1e-4
    beta_end: float = 2e-2


class GRUEncoder(nn.Module):
    def __init__(
        self,
        hidden_size: int,
        latent_dim: int,
        n_layers: int,
        dropout: float,
    ):
        super().__init__()
        self.in_proj = nn.Linear(VOCAB, hidden_size)
        self.gru = nn.GRU(
            input_size=hidden_size,
            hidden_size=hidden_size,
            num_layers=n_layers,
            batch_first=True,
            dropout=dropout if n_layers > 1 else 0.0,
        )
        self.to_mu = nn.Linear(hidden_size, latent_dim)
        self.to_logvar = nn.Linear(hidden_size, latent_dim)

    def forward(self, x_onehot: torch.Tensor):
        h = self.in_proj(x_onehot)
        out_top, h_n = self.gru(h)
        h_last = h_n[-1]
        mu = self.to_mu(h_last)
        logvar = self.to_logvar(h_last).clamp(-8.0, 8.0)
        return mu, logvar, out_top


class LatentConditionedGRUDecoder(nn.Module):
    def __init__(
        self,
        hidden_size: int,
        latent_dim: int,
        n_layers: int,
        dropout: float,
    ):
        super().__init__()
        self.token_embed = nn.Linear(VOCAB, hidden_size)
        self.z_to_h = nn.Linear(latent_dim, n_layers * hidden_size)
        self.gru = nn.GRU(
            input_size=hidden_size + latent_dim,
            hidden_size=hidden_size,
            num_layers=n_layers,
            batch_first=True,
            dropout=dropout if n_layers > 1 else 0.0,
        )
        self.to_logits = nn.Linear(hidden_size, VOCAB)

    def initial_hidden(self, z: torch.Tensor) -> torch.Tensor:
        return self.z_to_h(z).view(
            self.gru.num_layers,
            z.size(0),
            self.gru.hidden_size,
        )

    def step(
        self,
        z: torch.Tensor,
        current_token: torch.Tensor,
        h: torch.Tensor,
    ):
        emb = self.token_embed(current_token)
        dec_input = torch.cat([emb, z.unsqueeze(1)], dim=-1)
        out, h = self.gru(dec_input, h)
        logits = self.to_logits(out[:, -1, :])
        return logits, h


class GRUVAE(nn.Module):
    def __init__(self, cfg: ModelConfig):
        super().__init__()
        self.cfg = cfg
        self.enc = GRUEncoder(
            cfg.hidden_size,
            cfg.latent_dim,
            cfg.n_layers,
            cfg.dropout,
        )
        self.dec = LatentConditionedGRUDecoder(
            cfg.hidden_size,
            cfg.latent_dim,
            cfg.n_layers,
            cfg.dropout,
        )


class SinusoidalTimeEmbedding(nn.Module):
    def __init__(self, dim: int):
        super().__init__()
        if dim % 2:
            raise ValueError("time_dim must be even")
        self.dim = int(dim)

    def forward(self, t: torch.Tensor) -> torch.Tensor:
        half = self.dim // 2
        exponent = (
            -math.log(10000.0)
            * torch.arange(
                half,
                device=t.device,
                dtype=torch.float32,
            )
            / max(half - 1, 1)
        )
        frequencies = torch.exp(exponent)
        angles = t.float().unsqueeze(-1) * frequencies.unsqueeze(0)
        return torch.cat(
            [torch.sin(angles), torch.cos(angles)],
            dim=-1,
        )


class ResidualDenoiserBlock(nn.Module):
    def __init__(self, hidden_dim: int):
        super().__init__()
        self.norm = nn.LayerNorm(hidden_dim)
        self.fc1 = nn.Linear(hidden_dim, hidden_dim)
        self.fc2 = nn.Linear(hidden_dim, hidden_dim)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        h = self.norm(x)
        h = F.silu(self.fc1(h))
        h = self.fc2(h)
        return x + h


class LatentDenoiser(nn.Module):
    def __init__(
        self,
        latent_dim: int,
        cfg: DiffusionConfig,
    ):
        super().__init__()
        self.time_embedding = SinusoidalTimeEmbedding(cfg.time_dim)
        self.time_mlp = nn.Sequential(
            nn.Linear(cfg.time_dim, cfg.hidden_dim),
            nn.SiLU(),
            nn.Linear(cfg.hidden_dim, cfg.hidden_dim),
        )
        self.in_proj = nn.Linear(latent_dim, cfg.hidden_dim)
        self.blocks = nn.ModuleList(
            [
                ResidualDenoiserBlock(cfg.hidden_dim)
                for _ in range(cfg.n_blocks)
            ]
        )
        self.out_norm = nn.LayerNorm(cfg.hidden_dim)
        self.out_proj = nn.Linear(cfg.hidden_dim, latent_dim)

    def forward(
        self,
        h_t: torch.Tensor,
        t: torch.Tensor,
    ) -> torch.Tensor:
        h = self.in_proj(h_t)
        h = h + self.time_mlp(self.time_embedding(t))
        for block in self.blocks:
            h = block(h)
        h = F.silu(self.out_norm(h))
        return self.out_proj(h)


class LatentDiffusion(nn.Module):
    def __init__(
        self,
        latent_dim: int,
        cfg: DiffusionConfig,
    ):
        super().__init__()
        self.latent_dim = int(latent_dim)
        self.cfg = cfg
        self.denoiser = LatentDenoiser(latent_dim, cfg)

        betas = torch.linspace(
            cfg.beta_start,
            cfg.beta_end,
            cfg.train_steps,
            dtype=torch.float32,
        )
        alphas = 1.0 - betas
        alpha_bars = torch.cumprod(alphas, dim=0)

        self.register_buffer("betas", betas)
        self.register_buffer("alphas", alphas)
        self.register_buffer("alpha_bars", alpha_bars)

    @torch.no_grad()
    def ddim_sample(
        self,
        base_noise: torch.Tensor,
        inference_steps: int = 20,
    ) -> torch.Tensor:
        self.eval()
        n_train = self.cfg.train_steps
        inference_steps = min(
            max(int(inference_steps), 1),
            n_train,
        )

        timesteps = (
            torch.linspace(
                n_train - 1,
                0,
                inference_steps,
                device=base_noise.device,
            )
            .round()
            .long()
        )
        timesteps = torch.unique_consecutive(timesteps)

        h = base_noise
        for step_index, t_scalar in enumerate(timesteps):
            t = torch.full(
                (h.size(0),),
                int(t_scalar.item()),
                device=h.device,
                dtype=torch.long,
            )
            pred_noise = self.denoiser(h, t)
            alpha_bar_t = self.alpha_bars[t_scalar]
            pred_h0 = (
                h
                - torch.sqrt(1.0 - alpha_bar_t) * pred_noise
            ) / torch.sqrt(alpha_bar_t)

            if step_index == len(timesteps) - 1:
                h = pred_h0
                break

            t_prev = timesteps[step_index + 1]
            alpha_bar_prev = self.alpha_bars[t_prev]
            h = (
                torch.sqrt(alpha_bar_prev) * pred_h0
                + torch.sqrt(1.0 - alpha_bar_prev) * pred_noise
            )

        return h

    @torch.no_grad()
    def ddim_invert(
        self,
        h0: torch.Tensor,
        inference_steps: int = 20,
    ) -> torch.Tensor:
        self.eval()
        n_train = self.cfg.train_steps
        inference_steps = min(
            max(int(inference_steps), 1),
            n_train,
        )
        timesteps = (
            torch.linspace(
                0,
                n_train - 1,
                inference_steps,
                device=h0.device,
            )
            .round()
            .long()
        )
        timesteps = torch.unique_consecutive(timesteps)

        h = h0
        for step_index, t_scalar in enumerate(timesteps[:-1]):
            t = torch.full(
                (h.size(0),),
                int(t_scalar.item()),
                device=h.device,
                dtype=torch.long,
            )
            pred_noise = self.denoiser(h, t)
            alpha_bar_t = self.alpha_bars[t_scalar]
            pred_h0 = (
                h
                - torch.sqrt(1.0 - alpha_bar_t) * pred_noise
            ) / torch.sqrt(alpha_bar_t)

            t_next = timesteps[step_index + 1]
            alpha_bar_next = self.alpha_bars[t_next]
            h = (
                torch.sqrt(alpha_bar_next) * pred_h0
                + torch.sqrt(1.0 - alpha_bar_next) * pred_noise
            )
        return h


def standardize_mu(
    mu: torch.Tensor,
    latent_mean: torch.Tensor,
    latent_std: torch.Tensor,
) -> torch.Tensor:
    return (
        mu - latent_mean.to(mu.device)
    ) / latent_std.to(mu.device).clamp(min=1e-6)


def project_to_radius(
    eps: torch.Tensor,
    radius: float,
) -> torch.Tensor:
    return (
        eps
        / eps.norm(dim=-1, keepdim=True).clamp(min=1e-8)
        * float(radius)
    )


@torch.no_grad()
def encode_standardized_h0(
    vae: GRUVAE,
    peptides: Sequence[str],
    latent_mean: torch.Tensor,
    latent_std: torch.Tensor,
    device: torch.device,
    batch_size: int = 256,
) -> np.ndarray:
    chunks = []
    x_all = onehot_encode_peptides(peptides)
    for start in range(0, len(peptides), batch_size):
        x = x_all[start : start + batch_size].to(device)
        mu, _, _ = vae.enc(x)
        h0 = standardize_mu(
            mu,
            latent_mean,
            latent_std,
        )
        chunks.append(h0.cpu())
    return torch.cat(chunks, dim=0).numpy()


