RCSB_CIF_URL = "https://files.rcsb.org/download/{pdb}.cif"
STANDARD_AA = set("ACDEFGHIKLMNPQRSTVWY")
DEFAULT_INPUT_DIR = Path("metalpdb_all_metals_unique")
DEFAULT_INPUT_CSV = DEFAULT_INPUT_DIR / "metalpdb_all_metals_all_records.csv"
DEFAULT_OUTPUT_DIR = DEFAULT_INPUT_DIR / "binding_windows_len10"


