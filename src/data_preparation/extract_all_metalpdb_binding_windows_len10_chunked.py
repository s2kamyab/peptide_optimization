def ligands_from_nested_metals(row: pd.Series) -> List[Dict[str, Any]]:
    """Parse old-style 'metals' column: list of metal records with ligands."""
    if "metals" not in row.index or is_missing(row.get("metals")):
        return []

    metals_obj = parse_possible_literal(row.get("metals"))
    if isinstance(metals_obj, dict):
        metals_obj = [metals_obj]
    if not isinstance(metals_obj, list):
        return []

    out: List[Dict[str, Any]] = []
    for metal_rec in metals_obj:
        if not isinstance(metal_rec, dict):
            continue
        ligs = metal_rec.get("ligands", [])
        if isinstance(ligs, dict):
            ligs = [ligs]
        if not isinstance(ligs, list):
            continue
        for lig in ligs:
            if isinstance(lig, dict):
                lig2 = dict(lig)
                if "metal" not in lig2:
                    lig2["metal"] = metal_rec.get("metal") or metal_rec.get("symbol")
                out.append(lig2)
    return out


def ligands_from_ligands_column(row: pd.Series) -> List[Dict[str, Any]]:
    """Parse current API 'ligands' column if it is a list/dict string."""
    if "ligands" not in row.index or is_missing(row.get("ligands")):
        return []

    lig_obj = parse_possible_literal(row.get("ligands"))
    if isinstance(lig_obj, dict):
        return [lig_obj]
    if isinstance(lig_obj, list):
        return [x for x in lig_obj if isinstance(x, dict)]
    return []


def ligands_from_flattened_columns(row: pd.Series) -> List[Dict[str, Any]]:
    """
    Parse columns like ligands.0.chain, ligands.0.residue_pdb_number, etc.
    created by pd.json_normalize.
    """
    pattern = re.compile(r"^ligands\.(\d+)\.(.+)$")
    grouped: Dict[int, Dict[str, Any]] = defaultdict(dict)
    for col, val in row.items():
        m = pattern.match(str(col))
        if not m:
            continue
        idx = int(m.group(1))
        key = m.group(2)
        grouped[idx][key] = val
    return [grouped[i] for i in sorted(grouped)]


def extract_ligands(row: pd.Series) -> List[Dict[str, Any]]:
    """Return all ligand dicts found in a MetalPDB CSV row."""
    ligands: List[Dict[str, Any]] = []
    ligands.extend(ligands_from_nested_metals(row))
    ligands.extend(ligands_from_ligands_column(row))
    ligands.extend(ligands_from_flattened_columns(row))
    return ligands


def ligand_to_binding_residue(lig: Dict[str, Any], fallback_metal: Optional[str]) -> Optional[Tuple[str, int, str, Optional[str]]]:
    """
    Convert a ligand dictionary to (chain_id, residue_number, residue_name, metal_symbol).
    Keeps only standard amino-acid ligands.
    """
    chain = None
    for key in ["chain", "chain_id", "auth_asym_id", "label_asym_id", "asym_id"]:
        if key in lig and not is_missing(lig[key]):
            chain = normalize_chain_id(lig[key])
            break

    resnum = None
    for key in ["residue_pdb_number", "auth_seq_id", "residue_number", "resseq", "resnum", "residue_num"]:
        if key in lig and not is_missing(lig[key]):
            resnum = normalize_resseq(lig[key])
            break

    resname = None
    for key in ["residue", "resname", "res_name", "comp_id", "residue_name", "ligand"]:
        if key in lig and not is_missing(lig[key]):
            resname = str(lig[key]).strip().upper()
            break

    if chain is None or resnum is None or resname is None:
        return None

    aa1 = safe_three_to_one(resname)
    if aa1 == "X":
        return None

    metal = None
    for key in ["metal", "metal_symbol", "element", "metal_name"]:
        if key in lig and not is_missing(lig[key]):
            metal = clean_metal_symbol(lig[key])
            break
    if metal is None:
        metal = fallback_metal

    return chain, resnum, resname, metal


def extract_binding_residues_from_row(row: pd.Series, metal_col: Optional[str]) -> Dict[Tuple[str, str], set]:
    """
    Return {(metal_symbol, chain_id): set(residue_numbers)} for one MetalPDB row.
    """
    fallback_metal = clean_metal_symbol(row.get(metal_col)) if metal_col else None
    out: Dict[Tuple[str, str], set] = defaultdict(set)

    for lig in extract_ligands(row):
        parsed = ligand_to_binding_residue(lig, fallback_metal=fallback_metal)
        if parsed is None:
            continue
        chain, resnum, _resname, metal = parsed
        if metal is None:
            metal = fallback_metal or "UNKNOWN"
        out[(metal, chain)].add(resnum)

    return out


