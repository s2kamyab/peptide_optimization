# Main extraction
# ---------------------------------------------------------------------
def extract_binding_windows(
    input_csv: Path,
    output_dir: Path,
    window_len: int = 10,
    pad_termini: bool = False,
    cif_cache_dir: Optional[Path] = None,
    max_rows: Optional[int] = None,
    save_every_k: int = 1000,
    make_final_files: bool = False,
    clear_structure_cache_on_flush: bool = True,
) -> List[Path]:
    input_csv = Path(input_csv)
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    if cif_cache_dir is None:
        cif_cache_dir = output_dir / "cif_cache"
    cif_cache_dir.mkdir(parents=True, exist_ok=True)

    if save_every_k <= 0:
        raise ValueError("save_every_k must be a positive integer.")

    parts_dir = output_dir / "parts"
    parts_dir.mkdir(parents=True, exist_ok=True)
    manifest_rows: List[Dict[str, Any]] = []
    window_part_files: List[Path] = []
    failure_part_files: List[Path] = []
    part_idx = 1
    total_windows_written = 0
    total_failures_written = 0

    df = pd.read_csv(input_csv)
    if max_rows is not None:
        df = df.head(max_rows).copy()

    pdb_col = first_existing_column(df, ["pdb_code", "pdb", "pdb_id", "PDB", "PDB_ID"])
    metal_col = first_existing_column(df, ["query_metal", "metal", "metal_symbol", "Metal"])
    site_col = first_existing_column(df, ["site", "site_id", "id"])
    uniprot_col = first_existing_column(df, ["uniprot", "UniProt", "uniprot_id"])
    molecule_col = first_existing_column(df, ["molecule", "protein", "macromolecule", "name"])
    organism_col = first_existing_column(df, ["organism", "species"])

    if pdb_col is None:
        raise ValueError("Could not find a PDB column. Expected one of: pdb_code, pdb, pdb_id.")

    rows: List[Dict[str, Any]] = []
    failures: List[Dict[str, Any]] = []
    structure_cache: Dict[str, Any] = {}
    chain_cache: Dict[Tuple[str, str], Tuple[str, List[int], List[str]]] = {}

    print(f"Input rows: {len(df)}")
    print(f"Using PDB column: {pdb_col}")
    print(f"Using metal column: {metal_col}")
    print(f"Saving a new part CSV every {save_every_k} input rows")

    peptide_col = f"peptide_len{window_len}"
    label_col = f"binding_site_labels_len{window_len}"
    window_columns = [
        "source_row_index", "site", "metal", "pdb", "chain", "bind_resseq",
        "bind_residue_aa", "center_idx_in_chain_sequence", "window_start_idx",
        "window_end_idx", "center_pos_in_window", "uniprot", "molecule",
        "organism", peptide_col, label_col, "chain_sequence_length",
    ]
    failure_columns = [
        "row_index", "pdb", "metal", "chain", "bind_resseq", "center_idx", "reason",
    ]

    def flush_part(processed_until_row: int, force: bool = False) -> None:
        nonlocal rows, failures, part_idx, total_windows_written, total_failures_written
        nonlocal structure_cache, chain_cache

        if not force and not rows and not failures:
            return
        if force and not rows and not failures:
            return

        window_path = parts_dir / f"metalpdb_binding_windows_len{window_len}_part_{part_idx:06d}.csv"
        failure_path = parts_dir / f"metalpdb_binding_windows_len{window_len}_failures_part_{part_idx:06d}.csv"

        n_windows = write_chunk_csv(rows, window_path, columns=window_columns)
        n_failures = write_chunk_csv(failures, failure_path, columns=failure_columns)

        window_part_files.append(window_path)
        failure_part_files.append(failure_path)
        total_windows_written += n_windows
        total_failures_written += n_failures
        manifest_rows.append({
            "part": part_idx,
            "processed_until_input_row": processed_until_row,
            "window_csv": str(window_path),
            "failure_csv": str(failure_path),
            "n_windows": n_windows,
            "n_failures": n_failures,
        })

        print(
            f"Saved part {part_idx:06d}: windows={n_windows}, failures={n_failures}, "
            f"processed_until_row={processed_until_row}"
        )

        rows.clear()
        failures.clear()
        part_idx += 1

        if clear_structure_cache_on_flush:
            structure_cache.clear()
            chain_cache.clear()

    for i, row in df.iterrows():
        pdb_id = clean_pdb_id(row.get(pdb_col))
        if pdb_id is None:
            failures.append({"row_index": i, "reason": "missing_or_invalid_pdb"})
            continue

        binding_map = extract_binding_residues_from_row(row, metal_col=metal_col)
        if not binding_map:
            failures.append({"row_index": i, "pdb": pdb_id, "reason": "no_amino_acid_ligand_residues_parsed"})
            continue

        try:
            if pdb_id not in structure_cache:
                cif_path = download_cif(pdb_id, cif_cache_dir=cif_cache_dir)
                structure_cache[pdb_id] = load_structure(cif_path)
            structure = structure_cache[pdb_id]
        except Exception as e:
            failures.append({"row_index": i, "pdb": pdb_id, "reason": f"cif_download_or_parse_failed: {e}"})
            continue

        for (metal, chain_id), bind_resnums in binding_map.items():
            try:
                key = (pdb_id, chain_id)
                if key not in chain_cache:
                    chain_cache[key] = chain_sequence_and_resseqs_from_structure(structure, chain_id)
                seq, resseqs, resnames = chain_cache[key]
            except Exception as e:
                failures.append({
                    "row_index": i,
                    "pdb": pdb_id,
                    "metal": metal,
                    "chain": chain_id,
                    "reason": f"chain_not_found_or_parse_failed: {e}",
                })
                continue

            if not seq:
                failures.append({"row_index": i, "pdb": pdb_id, "chain": chain_id, "reason": "empty_chain_sequence"})
                continue

            # Map PDB author residue number to all sequence indices that carry that residue number.
            # Usually one index, but list is safer if insertion-code handling collapses residue IDs.
            resseq_to_indices: Dict[int, List[int]] = defaultdict(list)
            for idx, resseq in enumerate(resseqs):
                resseq_to_indices[int(resseq)].append(idx)

            for bind_resseq in sorted(bind_resnums):
                center_indices = resseq_to_indices.get(int(bind_resseq), [])
                if not center_indices:
                    failures.append({
                        "row_index": i,
                        "pdb": pdb_id,
                        "metal": metal,
                        "chain": chain_id,
                        "bind_resseq": bind_resseq,
                        "reason": "binding_residue_not_in_standard_chain_sequence",
                    })
                    continue

                for center_idx in center_indices:
                    win = centered_window(seq, center_idx, window_len=window_len, pad_termini=pad_termini)
                    if win is None:
                        failures.append({
                            "row_index": i,
                            "pdb": pdb_id,
                            "metal": metal,
                            "chain": chain_id,
                            "bind_resseq": bind_resseq,
                            "center_idx": center_idx,
                            "reason": "near_terminus_window_skipped",
                        })
                        continue

                    peptide, start, end, center_pos = win
                    rows.append({
                        "source_row_index": i,
                        "site": row.get(site_col) if site_col else None,
                        "metal": metal,
                        "pdb": pdb_id,
                        "chain": chain_id,
                        "bind_resseq": int(bind_resseq),
                        "bind_residue_aa": seq[center_idx] if 0 <= center_idx < len(seq) else None,
                        "center_idx_in_chain_sequence": int(center_idx),
                        "window_start_idx": int(start),
                        "window_end_idx": int(end - 1),
                        "center_pos_in_window": int(center_pos),
                        "uniprot": row.get(uniprot_col) if uniprot_col else None,
                        "molecule": row.get(molecule_col) if molecule_col else None,
                        "organism": row.get(organism_col) if organism_col else None,
                        f"peptide_len{window_len}": peptide,
                        f"binding_site_labels_len{window_len}": label_string(window_len, center_pos),
                        "chain_sequence_length": len(seq),
                    })

        if (i + 1) % 100 == 0:
            print(
                f"Processed {i + 1}/{len(df)} rows; "
                f"current-part windows={len(rows)}; total-written windows={total_windows_written}"
            )

        if (i + 1) % save_every_k == 0:
            flush_part(processed_until_row=i + 1)

    flush_part(processed_until_row=len(df), force=True)

    pd.DataFrame(manifest_rows).to_csv(
        output_dir / f"metalpdb_binding_windows_len{window_len}_manifest.csv",
        index=False,
    )

    if make_final_files:
        build_final_outputs_from_parts(
            window_part_files=window_part_files,
            failure_part_files=failure_part_files,
            output_dir=output_dir,
            window_len=window_len,
        )

    print("\nSaved chunked outputs:")
    print(f"  parts folder: {parts_dir}")
    print(f"  manifest: {output_dir / f'metalpdb_binding_windows_len{window_len}_manifest.csv'}")
    print(f"  total window rows written: {total_windows_written}")
    print(f"  total failure rows written: {total_failures_written}")
    if make_final_files:
        print("  final combined/deduplicated files were also created")
    else:
        print("  final combined/deduplicated files were skipped; use --make-final-files if needed")

    return window_part_files

def main() -> None:
    parser = argparse.ArgumentParser(
        description="Extract length-10 peptide windows centered on MetalPDB metal-binding residues."
    )
    parser.add_argument(
        "--input-csv",
        type=Path,
        default=DEFAULT_INPUT_CSV,
        help="Input CSV, usually metalpdb_all_metals_unique/metalpdb_all_metals_all_records.csv",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=DEFAULT_OUTPUT_DIR,
        help="Output folder for peptide-window CSV files.",
    )
    parser.add_argument("--window-len", type=int, default=10, help="Peptide window length. Default: 10")
    parser.add_argument(
        "--pad-termini",
        action="store_true",
        help="Pad near-terminus windows with X instead of skipping them.",
    )
    parser.add_argument(
        "--cif-cache-dir",
        type=Path,
        default=None,
        help="Optional CIF cache folder. Default: <output-dir>/cif_cache",
    )
    parser.add_argument(
        "--max-rows",
        type=int,
        default=None,
        help="Optional quick-test limit on input rows.",
    )
    parser.add_argument(
        "--save-every-k",
        type=int,
        default=1000,
        help="Save current rows to a new part CSV every K input rows. Default: 1000.",
    )
    parser.add_argument(
        "--make-final-files",
        action="store_true",
        help=(
            "After chunked extraction, also build combined, deduplicated, unique peptide-metal, "
            "summary, and failure CSVs. This uses more memory than chunked-only mode."
        ),
    )
    parser.add_argument(
        "--keep-structure-cache",
        action="store_true",
        help="Do not clear parsed structure/chain caches after each part. Faster but uses more RAM.",
    )
    args = parser.parse_args()

    extract_binding_windows(
        input_csv=args.input_csv,
        output_dir=args.output_dir,
        window_len=args.window_len,
        pad_termini=args.pad_termini,
        cif_cache_dir=args.cif_cache_dir,
        max_rows=args.max_rows,
        save_every_k=args.save_every_k,
        make_final_files=args.make_final_files,
        clear_structure_cache_on_flush=not args.keep_structure_cache,
    )


if __name__ == "__main__":
    main()
