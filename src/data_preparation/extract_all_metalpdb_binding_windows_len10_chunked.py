def download_cif(pdb_id: str, cif_cache_dir: Path, timeout_sec: float = 60.0, max_retries: int = 3) -> Path:
    pdb_id = pdb_id.lower()
    cif_cache_dir.mkdir(parents=True, exist_ok=True)
    out_path = cif_cache_dir / f"{pdb_id}.cif"
    if out_path.exists() and out_path.stat().st_size > 0:
        return out_path

    url = RCSB_CIF_URL.format(pdb=pdb_id)
    last_err = None
    for attempt in range(1, max_retries + 1):
        try:
            r = requests.get(url, timeout=timeout_sec)
            r.raise_for_status()
            out_path.write_bytes(r.content)
            return out_path
        except Exception as e:
            last_err = e
            if attempt < max_retries:
                time.sleep(0.5 * attempt)
    raise RuntimeError(f"Could not download CIF for {pdb_id}: {last_err}")


def load_structure(cif_path: Path):
    parser = MMCIFParser(QUIET=True)
    return parser.get_structure(cif_path.stem, str(cif_path))


def chain_sequence_and_resseqs_from_structure(structure: Any, chain_id: str) -> Tuple[str, List[int], List[str]]:
    """
    Build sequence and aligned author residue numbers for one chain.
    Returns sequence, residue_numbers, residue_names.
    """
    model = next(structure.get_models())
    if chain_id not in model:
        raise KeyError(f"Chain {chain_id} not found")

    chain = model[chain_id]
    seq_chars: List[str] = []
    resseqs: List[int] = []
    resnames: List[str] = []

    for res in chain:
        if not is_aa(res, standard=True):
            continue
        resname = res.get_resname().upper()
        aa1 = safe_three_to_one(resname)
        if aa1 == "X":
            continue
        seq_chars.append(aa1)
        resseqs.append(int(res.get_id()[1]))
        resnames.append(resname)

    return "".join(seq_chars), resseqs, resnames


def centered_window(sequence: str, center_idx: int, window_len: int, pad_termini: bool = False):
    """
    Return peptide window centered on center_idx.
    For window_len=10, binding residue is at index 4 by default.
    """
    if window_len <= 0:
        raise ValueError("window_len must be positive")

    left = window_len // 2 - 1 if window_len % 2 == 0 else window_len // 2
    right = window_len - 1 - left
    start = center_idx - left
    end = center_idx + right + 1

    if not pad_termini:
        if start < 0 or end > len(sequence):
            return None
        pep = sequence[start:end]
        center_pos = center_idx - start
        return pep, start, end, center_pos

    # Pad with X if window exceeds termini.
    raw_chars: List[str] = []
    for idx in range(start, end):
        if 0 <= idx < len(sequence):
            raw_chars.append(sequence[idx])
        else:
            raw_chars.append("X")
    pep = "".join(raw_chars)
    center_pos = center_idx - start
    return pep, start, end, center_pos


def label_string(window_len: int, center_pos: int) -> str:
    labels = [0] * window_len
    labels[center_pos] = 1
    return " ".join(map(str, labels))



