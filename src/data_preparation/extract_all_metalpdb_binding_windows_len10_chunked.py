def write_chunk_csv(
    rows: List[Dict[str, Any]],
    out_path: Path,
    columns: Optional[Sequence[str]] = None,
) -> int:
    """Write one chunk CSV and clear no external state. Returns rows written."""
    out_path.parent.mkdir(parents=True, exist_ok=True)
    if not rows:
        pd.DataFrame(columns=list(columns) if columns else None).to_csv(out_path, index=False)
        return 0
    df = pd.DataFrame(rows)
    if columns is not None:
        for col in columns:
            if col not in df.columns:
                df[col] = None
        df = df[list(columns)]
    df.to_csv(out_path, index=False)
    return len(df)


def iter_csv_files(files: Sequence[Path], chunksize: int = 100_000):
    """Yield dataframe chunks from a list of CSV files."""
    for path in files:
        if not path.exists() or path.stat().st_size == 0:
            continue
        try:
            for chunk in pd.read_csv(path, chunksize=chunksize):
                yield chunk
        except pd.errors.EmptyDataError:
            continue


def build_final_outputs_from_parts(
    window_part_files: Sequence[Path],
    failure_part_files: Sequence[Path],
    output_dir: Path,
    window_len: int,
    combine_chunksize: int = 100_000,
) -> None:
    """
    Build the same final CSVs as the original script from chunk files.

    This still stores deduplication keys in memory, but it avoids holding all raw
    rows in memory during extraction. If your dataset is extremely large, run
    without --make-final-files and deduplicate later with a database/Dask/Polars.
    """
    peptide_col = f"peptide_len{window_len}"
    all_csv = output_dir / f"metalpdb_binding_windows_len{window_len}_all_metals.csv"
    dedup_csv = output_dir / f"metalpdb_binding_windows_len{window_len}_all_metals_deduplicated.csv"
    peptide_metal_csv = output_dir / f"metalpdb_binding_windows_len{window_len}_unique_peptide_metal.csv"
    summary_csv = output_dir / f"metalpdb_binding_windows_len{window_len}_summary_by_metal.csv"
    failures_csv = output_dir / f"metalpdb_binding_windows_len{window_len}_failures.csv"

    # Combine raw chunks by streaming append.
    first = True
    for chunk in iter_csv_files(window_part_files, chunksize=combine_chunksize):
        chunk.to_csv(all_csv, mode="w" if first else "a", header=first, index=False)
        first = False
    if first:
        pd.DataFrame().to_csv(all_csv, index=False)

    first = True
    for chunk in iter_csv_files(failure_part_files, chunksize=combine_chunksize):
        chunk.to_csv(failures_csv, mode="w" if first else "a", header=first, index=False)
        first = False
    if first:
        pd.DataFrame().to_csv(failures_csv, index=False)

    # Deduplicate streamed chunks.
    dedup_cols = ["metal", "pdb", "chain", "bind_resseq", peptide_col]
    seen_dedup = set()
    seen_peptide_metal = set()
    first_dedup = True
    first_pep_metal = True

    # Summary counters based on deduplicated windows.
    summary = defaultdict(lambda: {
        "n_windows": 0,
        "unique_peptides": set(),
        "pdbs": set(),
        "uniprots": set(),
    })

    for chunk in iter_csv_files(window_part_files, chunksize=combine_chunksize):
        if chunk.empty or peptide_col not in chunk.columns:
            continue

        dedup_keep_rows = []
        pep_metal_keep_rows = []

        for row in chunk.to_dict("records"):
            key = tuple(row.get(c) for c in dedup_cols)
            if key not in seen_dedup:
                seen_dedup.add(key)
                dedup_keep_rows.append(row)

                metal = row.get("metal")
                summary[metal]["n_windows"] += 1
                summary[metal]["unique_peptides"].add(row.get(peptide_col))
                summary[metal]["pdbs"].add(row.get("pdb"))
                uni = row.get("uniprot")
                if not is_missing(uni):
                    summary[metal]["uniprots"].add(str(uni))

            pm_key = (row.get("metal"), row.get(peptide_col))
            if pm_key not in seen_peptide_metal:
                seen_peptide_metal.add(pm_key)
                pep_metal_keep_rows.append(row)

        if dedup_keep_rows:
            pd.DataFrame(dedup_keep_rows).to_csv(
                dedup_csv,
                mode="w" if first_dedup else "a",
                header=first_dedup,
                index=False,
            )
            first_dedup = False

        if pep_metal_keep_rows:
            pd.DataFrame(pep_metal_keep_rows).to_csv(
                peptide_metal_csv,
                mode="w" if first_pep_metal else "a",
                header=first_pep_metal,
                index=False,
            )
            first_pep_metal = False

    if first_dedup:
        pd.DataFrame().to_csv(dedup_csv, index=False)
    if first_pep_metal:
        pd.DataFrame().to_csv(peptide_metal_csv, index=False)

    summary_rows = []
    for metal, vals in summary.items():
        summary_rows.append({
            "metal": metal,
            "n_windows": vals["n_windows"],
            "n_unique_peptides": len(vals["unique_peptides"]),
            "n_pdb_structures": len(vals["pdbs"]),
            "n_uniprot": len(vals["uniprots"]),
        })
    summary_df = pd.DataFrame(summary_rows)
    if len(summary_df):
        summary_df = summary_df.sort_values(["n_windows", "n_unique_peptides"], ascending=False)
    summary_df.to_csv(summary_csv, index=False)

