def first_existing_column(df: pd.DataFrame, candidates: Sequence[str]) -> Optional[str]:
    """Return the first column name that exists in df."""
    for c in candidates:
        if c in df.columns:
            return c
    lower_map = {str(c).lower(): c for c in df.columns}
    for c in candidates:
        if c.lower() in lower_map:
            return lower_map[c.lower()]
    return None


def is_missing(x: Any) -> bool:
    if x is None:
        return True
    try:
        if isinstance(x, float) and math.isnan(x):
            return True
    except Exception:
        pass
    s = str(x).strip()
    return s == "" or s.lower() in {"nan", "none", "null"}


def parse_possible_literal(value: Any) -> Any:
    """Parse JSON/Python-literal strings safely; otherwise return original value."""
    if is_missing(value):
        return None
    if isinstance(value, (list, dict)):
        return value
    if not isinstance(value, str):
        return value

    text = value.strip()
    if not text:
        return None

    # Try JSON first, then Python literal strings produced by pandas CSV round-trips.
    for parser in (json.loads, ast.literal_eval):
        try:
            return parser(text)
        except Exception:
            continue
    return value


def safe_three_to_one(resname: str) -> str:
    """Convert 3-letter residue name to one-letter amino acid code."""
    if is_missing(resname):
        return "X"
    resname = str(resname).strip().upper()
    try:
        aa = seq1(resname, custom_map={})
    except Exception:
        return "X"
    aa = str(aa).strip().upper()
    if len(aa) != 1 or aa not in STANDARD_AA:
        return "X"
    return aa


def clean_pdb_id(value: Any) -> Optional[str]:
    if is_missing(value):
        return None
    s = str(value).strip().lower()
    # common cases: 1abc, 1ABC, ['1abc'] accidentally stringified, etc.
    m = re.search(r"[0-9][a-zA-Z0-9]{3}", s)
    return m.group(0).lower() if m else None


def clean_metal_symbol(value: Any) -> Optional[str]:
    if is_missing(value):
        return None
    v = parse_possible_literal(value)
    if isinstance(v, list) and v:
        v = v[0]
    if isinstance(v, dict):
        for k in ["metal", "symbol", "element", "name"]:
            if k in v and not is_missing(v[k]):
                v = v[k]
                break
    s = str(v).strip()
    m = re.search(r"[A-Za-z]{1,2}", s)
    return m.group(0).title() if m else None


def normalize_chain_id(chain: Any) -> Optional[str]:
    if is_missing(chain):
        return None
    chain = str(chain).strip()
    return chain if chain else None


def normalize_resseq(resnum: Any) -> Optional[int]:
    """Convert residue number to int. Handles strings like '123', '123A', '-1'."""
    if is_missing(resnum):
        return None
    text = str(resnum).strip()
    m = re.search(r"-?\d+", text)
    if not m:
        return None
    try:
        return int(m.group(0))
    except Exception:
        return None


